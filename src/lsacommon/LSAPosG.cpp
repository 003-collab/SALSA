// Parse a string from a single line in the LSA file.
// param line single line read from LSA file
// return true if successful
void LSAPosG::fromString(const string& line)
{
    if (line.empty()) return;

    modifiers.clearModifiers();

    int n, index;
    vector<string> F;

    std::deque<std::string> optionalParms;

    string str(line);                // copy const line
    stripTrailing(str,"\n");
    stripTrailing(str,"\r");
    stripTrailing(str," ");
    stripLeading(str," ");

    // Steal the General Notes before continuing.
    textNotes = QString::fromStdString(extractXMLFromString(str, RecordTags::TextNotes, true));
    // split into fields
    F = splitWithDoubleQuotes(str,' ');
    n = F.size();

    bool goodParse= true;

    //handle legacy AutogeneratedPoints.lsa file from v1.0.0 to 1.1.2
    vector<string>::iterator autogenKeywordIndex = std::find( F.begin(), F.end(), string("AUTOGEN") );
    if(autogenKeywordIndex!=F.end())
    {
        parseWarnings.push_back("Saving AUTOGEN POSG files to .lsa files is no longer supported.");
        F.pop_back();
    }
    vector<string>::iterator vscaKeywordIndex = std::find( F.begin(), F.end(), string("VSCA") );
    if(vscaKeywordIndex!=F.end())
    {
        index = vscaKeywordIndex-F.begin();

        std::string secondParm = F.at(index+1); // make a copy so upperCase won't change the value in F
        bool vscaValueUsed = (gnsstk::StringUtils::upperCase(secondParm) == "VALUE");


        if ( !vscaValueUsed )
        {
            optionalParms.push_back(F.at(index));
            optionalParms.push_back(F.at(index+1));

            F.pop_back();
            F.pop_back();
        }
        else
        {
            optionalParms.push_back(F.at(index));
            optionalParms.push_back(F.at(index+1));
            optionalParms.push_back(F.at(index+2));

            F.pop_back();
            F.pop_back();
            F.pop_back();
        }

        n = F.size();
    }
    if(optionalParms.size()>0)
    {
        goodParse = modifiers.parseOptionalParms(optionalParms, LSAType::POSG, label, &parseWarnings);
    }


    if(n < 4 )
    {
        addNumFieldsWarning(LSAType::POSC, label);
        return;
    }

    // Search for optional constraint modifiers and remove them from F
    std::string valueFltConFix;
    std::string valueNEU;

    if (isFltConFix(F[2]) && isNEU(F[3]) )
    {
        valueNEU = F.at(3);
        F.erase(F.begin() + 3);

        valueFltConFix = F.at(2);
        F.erase(F.begin() + 2);
    }
    else if (isFltConFix(F[2]))
    {
        valueFltConFix = F.at(2);
        F.erase(F.begin() + 2);
    }
    else if (isNEU(F[2]))
    {
        valueNEU = F.at(2);
        F.erase(F.begin() + 2);
    }
    n = F.size();
    // Note values for fixConFlt are set below after hasCovariance is parsed

    if (!valueNEU.empty())
    {
        validateString(valueNEU, LSAFieldType::FIXED_STATE, "n,e,u,ne,nu,eu,en,ue,un,neu,nue,enu,eun,uen,une");
    }
    if (!valueFltConFix.empty())
    {
        validateString(valueFltConFix, LSAFieldType::FIXED_STATE, "flt,con,fix");
    }
    setFixedConstraints(valueNEU);

    label = F[1];
    n = F.size();

    // Search the contents of the file line after the station name to see if the "ortho" flag
    // exists.
    vector<string>::const_iterator orthoIterator = std::find(std::next(F.begin(), 2),
                                                             F.end(), lsa::FLAG_ORTHOMETRIC);
    bool isOrthometric = false;
    unsigned int offsetVal;
    if(orthoIterator != F.end())
    {
        isOrthometric = true;
        heightIsEllipsoidal = false;
        offsetVal = 1;
    }

    else
    {
        offsetVal = 0;
    }

    if( (n == 8 && !isOrthometric) || (n==9 && isOrthometric) ) // decimal lat lon without covariance
    {
        useDecimalDegrees = true;
        latDecDeg = validateDoubleMinMax( F[2], LSAFieldType::LAT_DEC_DEG , -90, 90);
        latDir = validateString(          F[3], LSAFieldType::LAT_DIR,      "N,S,n,s" );
        lonDecDeg = validateDoubleMinMax( F[4], LSAFieldType::LAT_DEC_DEG,  -360, 360, true, true );
        lonDir = validateString(          F[5], LSAFieldType::LON_DIR,      "W,E,w,e" );

        height = validateDouble(          F[6], LSAFieldType::HEIGHT);
        heightUnits = validateString(     F[7], LSAFieldType::HEIGHT_UNITS, "cm,m,ft") ;

        hasCovariance = false;
    }
    else if( (n == 14 && !isOrthometric) || (n == 15 && isOrthometric) ) // decimal lat lon with covariance
    {
        useDecimalDegrees = true;
        latDecDeg = validateDoubleMinMax( F[2], LSAFieldType::LAT_DEC_DEG, -90, 90 );
        latDir = validateString(          F[3], LSAFieldType::LAT_DIR,     "N,S,n,s" );
        lonDecDeg = validateDoubleMinMax( F[4], LSAFieldType::LAT_DEC_DEG, -360, 360, true, true );
        lonDir = validateString(          F[5], LSAFieldType::LON_DIR,     "W,E,w,e" );

        height = validateDouble(          F[6], LSAFieldType::HEIGHT);
        heightUnits = validateString(     F[7], LSAFieldType::HEIGHT_UNITS, "cm,m,ft") ;

        hasCovariance = true;
        covnn = validateDouble( F[8 + offsetVal],  LSAFieldType::COVARIANCE );
        covne = validateDouble( F[9 + offsetVal],  LSAFieldType::COVARIANCE );
        covnu = validateDouble( F[10 + offsetVal], LSAFieldType::COVARIANCE );
        covee = validateDouble( F[11 + offsetVal], LSAFieldType::COVARIANCE );
        coveu = validateDouble( F[12 + offsetVal], LSAFieldType::COVARIANCE );
        covuu = validateDouble( F[13 + offsetVal], LSAFieldType::COVARIANCE );
    }
    else if( (n == 12 && !isOrthometric) || (n == 13 && isOrthometric) ) // DMS lat lon without covariance
    {
        useDecimalDegrees = false;
        latDeg = validateIntBool( latDMSIsNeg, F[2], LSAFieldType::LAT_DEG, -90,   90 );
        latMin = validateIntMinMax(    F[3], LSAFieldType::LAT_MIN,   0,   59 );
        latSec = validateDoubleMinMax( F[4], LSAFieldType::LAT_SEC, 0.0, 60.0, false, true);
        //don't allow 90 1' 1" (which will pass the above validation) - Fix to Bug #1212
//        validateDMSBool(latDMSIsNeg,latDeg,latMin,latSec,LSAFieldType::DMS,-90,90,false,false);
        LSARecord::validateDMSBool(latDMSIsNeg,latDeg,latMin,latSec,-90.0,90.0, &parseWarnings);
        latDir = validateString(       F[5], LSAFieldType::LAT_DIR, "n,s" );

        lonDeg = validateIntBool( lonDMSIsNeg, F[6], LSAFieldType::LON_DEG,  -359,  359 );
        lonMin = validateIntMinMax(    F[7], LSAFieldType::LON_DEG,    0,   59 );
        lonSec = validateDoubleMinMax( F[8], LSAFieldType::LON_SEC,  0.0, 60.0, false, true);
        lonDir = validateString(       F[9], LSAFieldType::LON_DIR, "w,e" );

        height = validateDouble(       F[10], LSAFieldType::HEIGHT);
        heightUnits = validateString(  F[11], LSAFieldType::HEIGHT_UNITS, "cm,m,ft") ;

        hasCovariance = false;
    }
    else if( (n == 18 && !isOrthometric) || (n==19 && isOrthometric) ) // DMS lat lon with covariance
    {
        useDecimalDegrees = false;

        latDeg = validateIntBool( latDMSIsNeg, F[2], LSAFieldType::LAT_DEG,   -90,   90 );
        latMin = validateIntMinMax(    F[3], LSAFieldType::LAT_MIN,   0,   59 );
        latSec = validateDoubleMinMax( F[4], LSAFieldType::LAT_SEC, 0.0, 60.0, false, true);
        //don't allow 90 1' 1" (which will pass the above validation) - Fix to Bug #1212
//        validateDMSBool(latDMSIsNeg,latDeg,latMin,latSec,LSAFieldType::DMS,-90,90,false,false);
        LSARecord::validateDMSBool(latDMSIsNeg,latDeg,latMin,latSec,-90.0,90.0, &parseWarnings);
        latDir = validateString(       F[5], LSAFieldType::LAT_DIR, "n,s" );

        lonDeg = validateIntBool( lonDMSIsNeg, F[6], LSAFieldType::LON_DEG,    -359,  359 );
        lonMin = validateIntMinMax(    F[7], LSAFieldType::LON_DEG,    0,   59 );
        lonSec = validateDoubleMinMax( F[8], LSAFieldType::LON_SEC,  0.0, 60.0, false, true);
        lonDir = validateString(       F[9], LSAFieldType::LON_DIR, "w,e" );

        height = validateDouble(       F[10], LSAFieldType::HEIGHT);
        heightUnits = validateString(  F[11], LSAFieldType::HEIGHT_UNITS, "cm,m,ft") ;

        hasCovariance = true;
        covnn = validateDouble(F[12 + offsetVal], LSAFieldType::COVARIANCE);
        covne = validateDouble(F[13 + offsetVal], LSAFieldType::COVARIANCE);
        covnu = validateDouble(F[14 + offsetVal], LSAFieldType::COVARIANCE);
        covee = validateDouble(F[15 + offsetVal], LSAFieldType::COVARIANCE);
        coveu = validateDouble(F[16 + offsetVal], LSAFieldType::COVARIANCE);
        covuu = validateDouble(F[17 + offsetVal], LSAFieldType::COVARIANCE);
    }
    else
    {
        addNumFieldsWarning(LSAType::POSG, label);
    }

    // set fixedState
    valueFltConFix = gnsstk::StringUtils::upperCase(valueFltConFix);
    if (valueFltConFix.empty() && hasCovariance)
    {
        fixedState = LSAFixedState::CONSTRAINED;
    }
    else if (valueFltConFix == "FLT")
    {
        fixedState = LSAFixedState::FLOATING;
    }
    else if (valueFltConFix == "CON")
    {
        fixedState = LSAFixedState::CONSTRAINED;
    }
    else if (valueFltConFix == "FIX")
    {
        fixedState = LSAFixedState::FIXED;
    }

    return;
}

//------------------------------------------------------------------------------------
// Set the constraints
// @param input any combination of E | N | U to indicate constrained axes
void LSAPosG::setFixedConstraints(string input)
{
    input = gnsstk::StringUtils::upperCase(input);

    // Reset constraints
    isNorthFixed = isEastFixed = isUpFixed = false;

    if ( input.find("N") !=std::string::npos )
    {
        isNorthFixed = true;
    }
    if ( input.find("E") !=std::string::npos )
    {
        isEastFixed = true;
    }
    if ( input.find("U") !=std::string::npos )
    {
        isUpFixed = true;
    }

    return;
}


//------------------------------------------------------------------------------------
// Output as a string for the LSA file.
// param out, an ostream reference to the output filestream or stringstream
void LSAPosG::writeLSAString(std::ostream & out) const
{
    std::string comment = isCommented ? "#" : "";

    out << comment << "POSG " << addQuotes(label);

    // FLT-CON-FIX
    if (isNorthFixed && isEastFixed && isUpFixed)
    {
        out << " Fix";
    }
    else if (fixedState == LSAFixedState::FLOATING)
    {
        out << " Flt";
    }
    else if (fixedState == LSAFixedState::CONSTRAINED)
    {
        out << " Con";
    }
    else if (fixedState == LSAFixedState::FIXED)
    {
        out << " Fix";
    }

    // NEU
    std::ostringstream neuOSS;
    if (isNorthFixed)
    {
        neuOSS << "N";
    }
    if (isEastFixed)
    {
        neuOSS << "E";
    }
    if (isUpFixed)
    {
        neuOSS << "U";
    }
    if (!neuOSS.str().empty())
    {
        out << " " << neuOSS.str();
    }

    // Lat and Lon

    int anglePrecision;
    out << std::fixed;
    if (useDecimalDegrees)
    {
        anglePrecision = grabNumDigits(getRecType(), lsa::UNITS_DEG);
        out << std::setprecision(anglePrecision);
        out << " " << latDecDeg << " " << latDir << " " << lonDecDeg << " " << lonDir;
    }
    else
    {
        anglePrecision = grabNumDigits(getRecType(), lsa::UNITS_SOA);
        out << std::setprecision(anglePrecision);
        std::string latSign = latDMSIsNeg ? "-" : "";
        out << " " << latSign << latDeg << " " << latMin << " " << latSec << " " << latDir;
        std::string lonSign = lonDMSIsNeg ? "-" : "";
        out << " " << lonSign << lonDeg << " " << lonMin << " " << lonSec << " " << lonDir;
    }

    // Height
    int heightPrecision = grabNumDigits(getRecType(), heightUnits);
    out << std::setprecision(heightPrecision) << " " << height << " " << heightUnits;
    if(!heightIsEllipsoidal)
    {
        out << " " << lsa::FLAG_ORTHOMETRIC;
    }

    // covariance
    if (hasCovariance)
    {
        out << " ...\n";
        int w = 18;
        out << std::scientific << std::setprecision(lsa::NUM_DECIMALS_COVARIANCE);
        out << comment << setw(w) << covnn << " " << setw(w) << covne << " " << setw(w) << covnu << " ...\n";
        out << comment << setw(w) << ""    << " " << setw(w) << covee << " " << setw(w) << coveu << " ...\n";
        out << comment << setw(w) << ""    << " " << setw(w) << ""    << " " << setw(w) << covuu;
    }

    std::string modString = modifiers.getLSAString();
    if (!modString.empty())
    {
        out << " ...\n";
        out << comment << modString;
    }
    
    if (!textNotes.isEmpty())
    {
        out << " ...\n";
        // put the text notes at the end of the record.
        out << RecordTags::TextNotes.first + textNotes.toStdString() + RecordTags::TextNotes.second;
    }
    
    out << "\n";

   return;
}

// Get a string to display in a given column in the Project Navigator
// @param the column number to display
// @return the string to display in the UI
std::string LSAPosG::getUIColumnData(int columnNumber) const
{
    std::string retVal = "";

    switch (columnNumber)
    {
    case 0:
        retVal = asTypeString();
        break;
    case 1:
        retVal = getUIName();
        break;
    case 2:
        // SCJ TODO: vsca refactoring needed
        // retVal = gnsstk::StringUtils::asString(groupVSCA * modifiers.getVSCAValue(), 3);
        break;
    case 3:
        retVal = getUIDetails();
        break;
    case 4:
        retVal = modifiers.getUIDetails();
        break;
    }

    return retVal;
}

