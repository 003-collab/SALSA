//------------------------------------------------------------------------------------
// Output as a string (one line) to display in the UI. Pure virtual
// @return a string to display in the UI
std::string LSAPosG::getUIDetails() const
{
    std::ostringstream oss;

    // fixed
    if ( (isNorthFixed && isEastFixed && isUpFixed) || fixedState == LSAFixedState::FIXED )
    {
        oss << " Fix";
    }
    else
    {
        if (isNorthFixed && isEastFixed)
        {
            oss << " NE";
        }
        else if (isNorthFixed && isUpFixed)
        {
            oss << " NU";
        }
        else if (isEastFixed && isUpFixed)
        {
            oss << " EU";
        }
        else if (isNorthFixed)
        {
            oss << " N";
        }
        else if (isEastFixed)
        {
            oss << " E";
        }
        else if (isUpFixed)
        {
            oss << " U";
        }
    }

    // Lat and Lon
    if (useDecimalDegrees)
    {
        oss << std::fixed << std::setprecision(5) ;
        oss << " " << setw(10) << latDecDeg << " " << latDir;
        oss << " " << setw(10) << lonDecDeg << " " << lonDir;
    }
    else
    {   oss << std::fixed << std::setprecision(3);
        std::string latSign = latDMSIsNeg ? "-" : "";
        oss << std::right << " " << setw(3) << latSign << latDeg << " " << setw(2) << latMin << " " << setw(6) << latSec << " " << latDir;

        std::string lonSign = lonDMSIsNeg ? "-" : "";
        oss << std::right << " " << setw(3) << lonSign << lonDeg << " " << setw(2) << lonMin << " " << setw(6) << lonSec << " " << lonDir;
    }

    // Height
    oss << std::fixed << std::setprecision(3);
    oss << " " << setw(8) << height << " " << heightUnits;


    std::string debug = oss.str();
    return debug;
}


void LSAPosG::fromECEFXYZCoords(double X, double Y, double Z)
{
    gnsstk::Position position(X, Y, Z, gnsstk::Position::Cartesian);

    useDecimalDegrees = true;

    // latitude
    latDecDeg = position.getGeodeticLatitude();
    latDir = "N";

    // longitude
    lonDecDeg = position.getLongitude();
    lonDir = "E";

    // initial height
    height = position.getHeight();
    heightUnits = "m";

    return;
}

void LSAPosG::getLatLonHeight(double &lonOut, double &latOut, double &heightOut) const
{
    double lat, lon;
    if (useDecimalDegrees)
    {
        lat = latDecDeg;
        lon = lonDecDeg;
    }
    else // lat and lon in DMS
    {
        lat = (double)::abs(latDeg) + (double)latMin/60 + latSec/3600;
        if(latDeg<0) lat *= -1.;

        lon = (double)::abs(lonDeg) + (double)lonMin/60 + lonSec/3600;
        if(lonDeg<0) lon *= -1.;
    }

    // Make sure lat is N and lon is E for use in gnsstk::position
    if ( latDir.compare("S") == 0)
    {
        lat *= -1;
    }
    if ( lonDir.compare("W") == 0)
    {
        lon = 360.0 - lon;
    }

    // convert length units to meters
    static const string M("m");
    double fact = convertTo(M, 1.0, heightUnits);
/*
    gnsstk::Position position(lat, lon, fact*height, gnsstk::Position::Geodetic);
    latOut = position.getGeodeticLatitude();
    lon = position.getLongitude();
    height = position.getHeight();
*/
    lonOut = lon;
    latOut = lat;
    heightOut = height*fact;

    return;
}

bool LSAPosG::referencesModifier(LSAType modifierType, std::string label) const
{
    if      (modifierType == LSAType::VSCA)  return (modifiers.getVSCALabel() == label);
    else if (modifierType == LSAType::UNCR) return (modifiers.getUncrLabel() == label);
    else if (modifierType == LSAType::HGHT)
    {
       return ( modifiers.getHeightFromLabel() == label || modifiers.getHeightToLabel() == label);
    }

    return false;
}

bool LSAPosG::hasValidCovariance() const
{
    if (isNorthFixed && isEastFixed && isUpFixed)
    {
        return true;
    }

    if (fixedState == LSAFixedState::FLOATING)
    {
        return true;
    }
    else if( fixedState == LSAFixedState::FIXED)
    {
        return true;
    }
    else if (fixedState == LSAFixedState::CONSTRAINED && hasCovariance)
    {
        bool covIsPositiveSemiDefinite = isPositiveSemiDefinite(covnn, covne, covnu, covee, coveu, covuu);

        if (covIsPositiveSemiDefinite)
        {
            return true;
        }
        else
        {
            return false;
        }
    }

    return false;
}

double LSAPosG::giveStandardLat() const
{
    double lat;
    useDecimalDegrees ? lat = latDecDeg : lat = DMSToDeg(latDMSIsNeg, latDeg, latMin, latSec);
    if(latDir.compare("S") == 0)
    {
        lat *= -1.0;
    }

    return lat;
}

double LSAPosG::giveStandardLon(bool forcePos) const
{
    double lon;
    useDecimalDegrees ? lon = lonDecDeg : lon = DMSToDeg(lonDMSIsNeg, lonDeg, lonMin, lonSec);
    if(lonDir.compare("W") == 0)
    {
        lon *= -1.0;
    }

    if(forcePos && lon < 0.0)
    {
        lon += 360.0;
    }

    return lon;
}

