int LSAFile::parseLSAStream(stringstream& ss, LSAInclude* currentInclude /* = nullptr */,
                            bool currentIsActive /* = false */, int childPosition /* = -1 */,
                            QList<LSARecord*>* newRecords /* = nullptr */)
{
    if(currentInclude == nullptr)
    {
        currentInclude = rootInclude;
    }
    int lineCounter = 0;
    // read loop
    createdWithSalsaVersion = std::string("UNKNOWN");//Here in case user hand-edited a text file, and there is no "Created ..." string.
    string line, word;
    while(1)
    {
        line = string("");
        getline(ss,line);
        lineCounter++;

        if (line.substr(0, 7) == "Created")
        {
            createdWithSalsaVersion = parseCreatedWithVersionFromString(line);

            auto supportedVersionString = parseBackwardCompatibilityVersionFromString(line);
            if(supportedVersionString.empty())
            {
                // There is no backward compatibility string, just continue parsing.
                continue;
            }
            std::vector<std::string> supportedStrings = gnsstk::StringUtils::split(supportedVersionString,'.');
            // Make sure there are only digits and '.''s in the string
            bool bValidBackPatVersion = true;
            for(const auto& supString : supportedStrings)
            {
                if(!isDigitString(supString))
                {
                    bValidBackPatVersion = false;
                    break;
                }
            }
            // If it's not already found to be bad, then check to make sure that the number of supportedStrings is 3
            bValidBackPatVersion = bValidBackPatVersion ? supportedStrings.size() == 3 : false;
            // If the backwards compatibility version isn't SEMVER, just pretend it doesn't exist
            if(!bValidBackPatVersion)
            {
                continue;
            }

            int minSupportedMajor;
            int minSupportedMinor;
            int minSupportedPatch;
            int lsaVersionMajor;
            int lsaVersionMinor;
            int lsaVersionPatch;
            bool versionIsValid = false;

            minSupportedMajor = gnsstk::StringUtils::asInt(supportedStrings[0]);
            minSupportedMinor = gnsstk::StringUtils::asInt(supportedStrings[1]);
            minSupportedPatch = gnsstk::StringUtils::asInt(supportedStrings[2]);

            lsaVersionMajor = gnsstk::StringUtils::asInt(LSAVERSION_MAJOR);
            lsaVersionMinor = gnsstk::StringUtils::asInt(LSAVERSION_MINOR);
            lsaVersionPatch = gnsstk::StringUtils::asInt(LSAVERSION_PATCH);

            if (lsaVersionMajor > minSupportedMajor )
            {
                versionIsValid = true;
            }

            if (lsaVersionMajor == minSupportedMajor && lsaVersionMinor > minSupportedMinor)
            {
                versionIsValid = true;
            }

            if (lsaVersionMajor == minSupportedMajor &&
                lsaVersionMinor == minSupportedMinor &&
                lsaVersionPatch >= minSupportedPatch )
            {
                versionIsValid = true;
            }

            if (versionIsValid)
            {
                // We are reading the file with a valid version of salsa, so continue parsing
                continue;
            }
            else
            {
                // Version checking failed.  Push an warning to the status window.
                //std::string statusMessage = "Parse Error - " + filename + " requires SALSA version " + supportedVersionString +".";
                std::string statusMessage = "Parse Error - <> requires SALSA version " + supportedVersionString +".";
                errorsAndWarnings.push_back(statusMessage);

                // Set a warning on the include record
                std::string warningMessage = "File requires SALSA version of at least " + supportedVersionString;
                currentInclude->warningMessages_persistent.insert(warningMessage);

                // Stop parsing.
                return false;
            }
        }

        bool lineIsCommented = false;
        bool goodParse = false;
        LSARecord* newRecord = nullptr;
        try
        {
            // TD need better handling of read failures : return -x
            if((ss.eof() || !ss.good()) && line.empty()) break;

            stripTrailing(line,"\n");
            stripTrailing(line,"\r");
            stripTrailing(line," ");

            lineIsCommented = (line.empty() || line[0] == '#');
            if (lineIsCommented && line[0] == '#')
            {
                line = line.substr(1); // strip the leading #
            }

            // Handle blank lines before concatenating continued lines
            if( line.empty() && !lineIsCommented)
            {
                LSAType lsaType(LSAType::COMMENT);
                newRecord = insertNewRecord(lsaType, line, currentInclude, lineIsCommented, currentIsActive);
                continue;
            }

            // look for last_word='...' and concatenate additional lines as needed
            handleLineContinuation(ss, line, lineCounter, lineIsCommented);

            word = gnsstk::StringUtils::upperCase(firstWord(line, ' '));

            // Parse the individual records types
            if(word == "--INCLUDE")
            {
                LSAType lsaType = LSAType::INCLUDE;

                std::string newFile;
                std::vector<std::string> modifierStrings;
                // cut out the text notes so that it isn't considered as a modifier.
                auto genNotes = extractXMLFromString(line, RecordTags::TextNotes, true);
                parseIncludeFilename(line, newFile, modifierStrings);

                // Note we pass includeFilename here, not line
                // TODO: remove childPosition and isAutogenerated when LSAInclude::fromString is refactored
                int isAutogenerated = false;
                newRecord = insertNewRecord(lsaType, newFile, currentInclude, lineIsCommented, currentIsActive, childPosition, isAutogenerated, modifierStrings, genNotes);

                if (newRecord != NULL)
                {
                    // parse the modifiers
                    LSAInclude* newInclude = static_cast<LSAInclude*>(newRecord);
                    newInclude->parseModifiers(modifierStrings);
                    goodParse = true;
                }
            }
            else
            {
                LSAType lsaType;
                lsaType.fromString(word);
                newRecord = insertNewRecord(lsaType, line, currentInclude, lineIsCommented, currentIsActive, childPosition);
                goodParse = ( newRecord != NULL);
            }
        }
        catch(...)
        {
            goodParse = false;
        }

        if(!goodParse || newRecord == NULL || newRecord->hasParseWarnings())
        {
            // if we failed to make a new record out of the line or it was commented, then add it as a comment
            if (lineIsCommented || newRecord == nullptr)
            {
                if (!line.empty())
                    line = "#" + line;

                newRecord = insertNewRecord(LSAType::COMMENT, line, currentInclude, lineIsCommented, currentIsActive, childPosition);
            }
            else if (newRecord != NULL && newRecord->hasParseWarnings())
            {
                // For record with a parse warning, do the following:
                // 1) Note that newRecord (assigned above) has not been inserted into the lsaTree
                // 2) Insert the record as a comment
                // 3) Attach the parse warnings from newRecord to the new comment
                // 4) Push the parse warnings to the user
                line = "# " + lsa::PARSE_WARNING + " - " + line;
                bool lineNotCommented = false;
                bool lineIsActive = true;
                auto parseWarningsCpy = newRecord->parseWarnings;
                delete newRecord;
                newRecord = nullptr;
                newRecord = insertNewRecord(LSAType::COMMENT, line, currentInclude, lineNotCommented, lineIsActive);
                for (size_t i = 0; i < parseWarningsCpy.size(); ++i)
                {
                    std::string warning = parseWarningsCpy[i];
                    newRecord->parseWarnings.push_back(warning);
                }
                newRecord->warningMessages_persistent.insert( MESSAGE_PARSE_WARNING );
            }
        }

        if(newRecords && newRecord)
        {
            newRecords->append(newRecord);
            // Make sure that the next record goes after the one we've just added
            if(childPosition > -1)
            {
                ++childPosition;
            }
        }

    } // end read loop
    return lineCounter;
}

