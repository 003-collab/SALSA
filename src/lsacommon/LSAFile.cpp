bool LSAFile::isProjectDirGeoid(const string &fileName) const
{
    QString projPath=QString::fromStdString(getPathWithoutFileName(fileName)+"/geoid");
    QString configFileName = getConfigName(fileName);
    ifstream configFile;
    configFile.open(configFileName.toStdString().c_str(),ios::in);
    if(!configFile.is_open())
        return false;
    string line;
    while(getline(configFile,line)){
        if(line.substr(0,11) == string("--geoidfile")){
            configFile.close();
            QString geoidFile = QString::fromStdString(line.substr(12,line.length()-1));
            QDir projDir(projPath);
            QStringList projFiles = projDir.entryList();
            if (projFiles.contains(geoidFile))
                return true;
            else
                return false;
        }
    }
    return false;
}

