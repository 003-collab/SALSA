QString LSAFile::getGeoidFileName(const QString &fileName)
{
    QString returnStr = QString("");
    QString configFileName = getConfigName(fileName);

    std::ifstream istrm;
    istrm.open(configFileName.toStdString().c_str(),std::ios::in);
    if(!istrm.is_open())
       return QString("");
    std::string line;
    std::vector<std::string> parts;

    while(1)
    {
       line = std::string("");
       getline(istrm,line);
       gnsstk::StringUtils::stripTrailing(line,'\r');
       gnsstk::StringUtils::stripTrailing(line,'\n');
       if((istrm.eof() || !istrm.good()) && line.empty()) break;
       if(line.empty())
           continue;

       if(line.at(0)!='#')
       {
           if(line.find("--geoidfile")!=std::string::npos)
           {
               parts = gnsstk::StringUtils::splitWithDoubleQuotes(line,' ');
               if(parts.size() < 2)
               {
                   pushWarning("No geoid file specified in the project .cfg file.");
               }
               else
               {
                   returnStr = QString::fromStdString(parts[1]);
               }
               break;
           }
       }
    }
    istrm.close();
    return returnStr;
}

QString LSAFile::getConfigName(const std::string &fileName) const
{
    return getConfigName(QString::fromStdString(fileName));
}

QString LSAFile::getConfigName(const QString &fileName) const
{
    QString configFileName;
    if(fileName.lastIndexOf(".") <= fileName.lastIndexOf("/"))//case when no extension on file
    {
        configFileName = fileName + QString(".cfg");
    }
    else
    {
        configFileName = fileName.left(fileName.lastIndexOf(".")) + QString(".cfg");
    }
    return configFileName;
}

bool LSAFile::isFileVersionCurrent(std::string salsaVersion)
{
    QString fileVer = QString::fromStdString(createdWithSalsaVersion);
    QString salsaVer = QString::fromStdString(salsaVersion);

    if(fileVer == QString("UNKNOWN") || fileVer == QString(""))
        return false;

    else if(fileVer == QString("Initial"))
        fileVer = salsaVer;

    QStringList fileVerPieces = fileVer.split(".");
    QStringList salsaVerPieces = salsaVer.split(".");
    // SEMVER specifies 3 components (Major.Minor.Patch)
    if(fileVerPieces.length() < 3 || salsaVerPieces.length() < 3)
        return false;

    int createdWithSalsaVersionMajor = fileVerPieces[0].toInt();
    int createdWithSalsaVersionMinor = fileVerPieces[1].toInt();
    int createdWithSalsaVersionPatch = fileVerPieces[2].toInt();
    int salsaVersionMajor = salsaVerPieces[0].toInt();
    int salsaVersionMinor = salsaVerPieces[1].toInt();
    int salsaVersionPatch = salsaVerPieces[2].toInt();

    if(salsaVersionMajor > createdWithSalsaVersionMajor)
        return false;
    else if(salsaVersionMinor > createdWithSalsaVersionMinor)
        return false;
    else if(salsaVersionPatch > createdWithSalsaVersionPatch)
        return false;
    else
        return true;
}

