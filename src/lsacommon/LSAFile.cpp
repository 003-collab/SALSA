// -----------------------------------------------------------------------------------
// Open and read a .LSA file, parse the contents and fill the data vectors.
// param filename file name
// param badrecs return vector<string> of records that could not be parsed
// return the number of records successfully read and parsed, or an error code
// throw if if reading failed
bool LSAFile::read(const string& absolutePath)
{
try
{
    // read and parse the file

    rootInclude = new LSAInclude(absolutePath, absolutePath, false);
    includedLSAFiles.insert(absolutePath);

    // Set the project directory
    QFileInfo fileInfo(QString::fromStdString(absolutePath));

    projectDirectory = fileInfo.absoluteDir().absolutePath().toStdString();

    bool rootIncludeIsActive = true;
    bool rootIncludeIsCommented = false;
    return readAndParseLSAfile(absolutePath, rootInclude, NULL, rootIncludeIsCommented, rootIncludeIsActive);
}
catch(Exception& e) { GNSSTK_RETHROW(e); }
}

// -----------------------------------------------------------------------------------
// Open, read and parse a .LSA file, filling a vector of pointers to LSArecord.
// param filename file name
// throw if file cannot be opened
bool LSAFile::readAndParseLSAfile(std::string filename, LSAInclude* currentInclude, LSAInclude* parentInclude, bool recordIsCommented, bool currentIsActive)
{
try
{
    if (currentInclude->isAutogenerated)
    {
        // Don't attempt to read and parse an autogenerated include record
        return false;
    }

    int lineCounter = 0;
    ifstream istrm;
    std::string fullFileName;
    if(pathIsRelative(filename))
        fullFileName = currentInclude->getAbsolutePath();
    else
        fullFileName = filename;
    istrm.open(fullFileName.c_str(), ios::in);

    // BAND-AID TO SUPPORT PRE-V1.3.0 PROJECTS! (bug 987)
    // Prior to version 1.3.0 there was a bug that could dubplicate child paths inside the full file path.
    // This could cause paths to be saved as projectDir/childDir/childDir/file.proj instead of projectDir/childDir/file.proj
    // The code below checks for this duplication if we can't open a file.
    // Specfically, it tries to open the file at projectDir/childPath instead of parentDir/childPath.  If it finds a file at
    // that path, it opens it.  Salsa will then save the path to the file correctly the next time the file is saved.
    if(!istrm.is_open())
    {
        //check to see if relative path and not just a file name
        if(pathIsRelative(filename) &&
           ((filename.find('/') != string::npos) || (filename.find('\\') != string::npos))
           )
        {
            std::string actualFullFileName = getAbsolutePathFromIncludePath(projectDirectory,filename);
            istrm.open(actualFullFileName.c_str(), ios::in);
            //we found a file at an incorrect path.  Fix the path.
            if(istrm.is_open() && (parentInclude != NULL))
            {
                 filename = getAbsoluteChildPath(actualFullFileName, parentInclude->getAbsolutePath());
                currentInclude->setLSAPath(filename);
                currentInclude->setAbsolutePath(actualFullFileName);
            }
        }
    }

    // return if we couldn't open the file
    if(!istrm.is_open())
    {
        if (currentIsActive && !recordIsCommented)
        {
            // set the error message to display a warning icon in the tree view
            currentInclude->warningMessages_persistent.insert( MESSAGE_FILE_NOT_FOUND );

            // push a parse warning
            std::string message = "Could not open included file: " + addQuotes(filename);
            pushBadRecord(filename, lineCounter, message);
        }
        return false;
    }

    // read loop
    createdWithSalsaVersion = std::string("UNKNOWN");//Here in case user hand-edited a text file, and there is no "Created ..." string.
    string line, word;

    stringstream ss;
    ss << istrm.rdbuf();

    lineCounter = parseLSAStream(ss, currentInclude, currentIsActive);

    if(lineCounter <= 2 && createdWithSalsaVersion=="UNKNOWN")
    {
        createdWithSalsaVersion = std::string("Initial");
    }

   istrm.close();
   return true;
}
catch(Exception& e)
{
    GNSSTK_RETHROW(e);
}
}

//GuiModel::parseIncludeFilename should duplicate this
void LSAFile::parseIncludeFilename(std::string line, std::string &newFile, std::vector<std::string> &modifierStrings)
{
    int n;
    vector<string> F;

    string str(line);                // copy const line
    stripTrailing(str,"\n");
    stripTrailing(str,"\r");
    stripTrailing(str," ");
    stripLeading(str," ");

    // split into fields
    F = gnsstk::StringUtils::splitWithDoubleQuotes(str,' ');
    n = F.size();

    if (n < 2)
    {
        newFile = std::string("");
        return;
    }

    newFile = F[1];

    if (n >2)
    {
        for (size_t i = 2; i < n; ++i )
        {
            modifierStrings.push_back(F.at(i));
        }
    }

    return;

}

