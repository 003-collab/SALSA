void LSAFile::saveLSAIncludeRecord(LSAInclude *parent)
{
    try
    {

        if (!parent)
        {
            return;
        }

        // don't try to save the file if the record has a file not found warning
        bool hasFileNotFoundWarning = (parent->warningMessages_generated.find(MESSAGE_FILE_NOT_FOUND) != parent->warningMessages_generated.end() );
        if (hasFileNotFoundWarning)
        {
            return;
        }

        // open the lsa file for writing, discarding anything already there
        // TODO: what if the file is already opened?
        //std::string filename = parent->getAbsoluteFilename(projectDirectory);
        std::string filename = parent->getAbsolutePath();
        Q_ASSERT(!filename.empty());

        //Fix to Bug #1521
        QDateTime lastModified;
        QFileInfo pre_check(QString::fromStdString(filename));
        if(pre_check.exists() && pre_check.isFile())
        {
            lastModified = pre_check.lastModified();
        }
        else
        {
            lastModified = QDateTime::currentDateTime();
        }

        std::fstream lsaFile;
        lsaFile.open(filename.c_str(), std::fstream::out | std::fstream::trunc);
        lsaFile << LSAVERSION_FILE_STRING << std::endl;

        std::list<LSARecord*> & records = parent->childRecords;

        for (std::list<LSARecord*>::iterator iter = records.begin(); iter != records.end(); ++iter )
        {
            LSARecord* lsaRecord = *iter;

            if (lsaRecord->hasParseWarnings() && lsaRecord->getRecType() == LSAType::COMMENT)
            {
                LSAComment *lsaComment = static_cast<LSAComment*>(lsaRecord);
                std::string parseWarningLine = lsaComment->lineContents;
                std::string lineToWrite;
                std::string warningToken = "Parse Warning - ";
                if (parseWarningLine.find(warningToken) != std::string::npos)
                    lineToWrite = parseWarningLine.substr(warningToken.size() + 2); // trim "Parse Warning - " from front of string
                else
                    lineToWrite = parseWarningLine; // Should never do this

                lsaFile << lineToWrite << std::endl;
            }
            else if(lsaRecord->getRecType() == LSAType::INCLUDE)
            {
                LSAInclude *lsaInclude = static_cast<LSAInclude *>(lsaRecord);
                if(!lsaInclude->isAutogenerated)
                {
                    lsaRecord->writeLSAString(lsaFile);
                    saveLSAIncludeRecord(lsaInclude);
                }
            }
            else
            {
                // for all other records, try to write it to the lsaFile
                lsaRecord->writeLSAString(lsaFile);
            }
        }
        lsaFile.close();
        //Fix to Bug #1521
        QFileInfo post_check(QString::fromStdString(filename));
        if(!post_check.exists() || !post_check.isFile())
        {
            std::ostringstream oss;
            oss << "Warning - failure to write " << filename << ".";
            pushWarning(oss.str());
        }
        else if(post_check.lastModified() <= lastModified)
        {
            std::ostringstream oss;
            oss << "Warning - failure to write " << filename << ".";
           pushWarning(oss.str());
        }
    }
    catch (Exception &e)
    {
        GNSSTK_RETHROW(e);
    }
}

LSARecord* LSAFile::insertNewRecord(LSAType recordType,     std::string line, LSAInclude* parentIncludeRecord,
                                    bool recordIsCommented, bool parentIsActive,
                                    int position,           bool isAutogenerated, std::vector<std::string> modifierStringsForInclude,
                                    std::string generalTextNotes)
{
    // if we weren't passed a position, insert the record as the last child
    if (position == -1)
    {
        position = parentIncludeRecord->childRecords.size();
    }

    // Create a new record of type recordType
    LSARecord *recordPtr;

    switch(recordType.getLSAtype())
    {
    case LSAType::INCLUDE:
    {
       // Get the parent and included filenames
       std::string absParentPath = parentIncludeRecord->getAbsolutePath();

       QFileInfo parentFileInfo(QString::fromStdString(absParentPath));
       QDir parentDir = parentFileInfo.absoluteDir();

       QString childLSAPath = QString::fromStdString(line);
       std::string absChildPath = parentDir.filePath(childLSAPath).toStdString();

       // Check if the new included file is already in the project
       if (includedLSAFiles.find(absChildPath) != includedLSAFiles.end())
       {
           std::string message = "File included multiple times: " + absChildPath;
           pushBadRecord(absParentPath, message);

           return NULL;
       }
       else
       {
           includedLSAFiles.insert(absChildPath);
       }

       // Create the new include record
       LSAInclude *lsaInclude = new LSAInclude(childLSAPath.toStdString(), absChildPath, false);

       // If the include is autogenerated, set the autogenerated flag and clear errant warnings
       lsaInclude->isAutogenerated = isAutogenerated;
       if (isAutogenerated || (lsaInclude->getLSAPath() == string("initial_coordinates.lsa"))) lsaInclude->warningMessages_generated.clear();

       // parse modifier strings if present
       if (modifierStringsForInclude.size() > 0)
           lsaInclude->parseModifiers(modifierStringsForInclude);

       // flag the include with a parseWarning if no filename is provided
       if (line.empty())
       {
           std::string message = "No filename provided for INCLUDE record.";
           lsaInclude->parseWarnings.push_back(message);
       }

       // Parse the included file and insert all of its children
       bool enableChildren = (parentIsActive && !recordIsCommented);
       ifstream fileOnDisk(absChildPath.c_str());
       bool fileOnDiskExists = fileOnDisk.good();
       fileOnDisk.close();
       if((lsaInclude->getLSAPath() != string("initial_coordinates.lsa") || fileOnDiskExists) && //don't try to parse newly created file
               !lsaInclude->hasParseWarnings() )
       {
           readAndParseLSAfile(line, lsaInclude, parentIncludeRecord, recordIsCommented, enableChildren);
       }

       // All of the other record types use their fromString method to assign textNotes, but we have
       // to do it like this for LSAInclude because its fromString still needs refactored.
       lsaInclude->textNotes = QString::fromStdString(generalTextNotes);

       recordPtr = dynamic_cast<LSARecord *>(lsaInclude);
       break;
    }
    case LSAType::CONFIG:
    {
       LSAConfig *ptr = new LSAConfig();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::UNCR:
    {
       LSAUncertainty *lsaUncrPtr = new LSAUncertainty();
       lsaUncrPtr->fromString(line);
       std::string label = lsaUncrPtr->label;
       recordPtr = dynamic_cast<LSARecord *>(lsaUncrPtr);

       insertMapValue(recordType, label, recordPtr, recordIsCommented, parentIsActive);
       break;
    }
    case LSAType::HGHT:
    {
       LSAHeight *lsaHeight = new LSAHeight();
       lsaHeight->fromString(line);
       std::string label = lsaHeight->label;
       recordPtr = dynamic_cast<LSARecord *>(lsaHeight);

       insertMapValue(recordType, label, recordPtr, recordIsCommented, parentIsActive);
       break;
    }
    case LSAType::VSCA:
    {
       LSAVarScaling *lsaVarPtr = new LSAVarScaling();
       lsaVarPtr->fromString(line);
       std::string label = lsaVarPtr->label;
       recordPtr = dynamic_cast<LSARecord *>(lsaVarPtr);

       insertMapValue(recordType, label, recordPtr, recordIsCommented, parentIsActive);

       // If we are inserting a vsca child of the root include, check for the appliedToParent flag
       // and apply it if present
       if (parentIncludeRecord == rootInclude && lsaVarPtr->isAppliedToParent)
       {
           parentIncludeRecord->modifiers.setVSCAData(label);
       }
       break;
    }
    case LSAType::POSG:
    {
       LSAPosG *lsaPosG = new LSAPosG();
       lsaPosG->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(lsaPosG);
       if(!lsaPosG->isAutogenerated)//handle legacy AutogeneratedPoints.lsa file from v1.0.0 to 1.1.2
           recordPtr->setIsAutogenerated(isAutogenerated);
       insertMapValue(recordType, lsaPosG->label, recordPtr, recordIsCommented, parentIsActive);
       break;
    }
    case LSAType::POSC:
    {
       LSAPosC *lsaPosC = new LSAPosC();
       lsaPosC->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(lsaPosC);
       insertMapValue(recordType, lsaPosC->label, recordPtr, recordIsCommented, parentIsActive);
       break;
    }
    case LSAType::HDIF:
    {
       LSAHeightDiff *ptr = new LSAHeightDiff();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::AZIM:
    {
       LSAAzimuth *ptr = new LSAAzimuth();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::HANG:
    {
       LSAHAngle *ptr = new LSAHAngle();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::ZANG:
    {
       LSAZAngle *ptr = new LSAZAngle();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::VANG:
    {
       LSAVAngle *ptr = new LSAVAngle();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::DXYZ:
    {
       LSADelta *ptr = new LSADelta();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::DIST:
    {
       LSADist *ptr = new LSADist();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::HDIR:
    {
       LSAHDir *ptr = new LSAHDir();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::COMMENT:
    {
       LSAComment *ptr = new LSAComment();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);

       recordIsCommented = false; // don't disable comment records
       break;
    }
    case LSAType::DGRP:
    {
       LSADirGroup *lsaDirGroupPtr = new LSADirGroup();
       lsaDirGroupPtr->fromString(line);
       std::string label = lsaDirGroupPtr->label;
       recordPtr = dynamic_cast<LSARecord *>(lsaDirGroupPtr);
       insertMapValue(recordType, label, recordPtr, recordIsCommented, parentIsActive);
       break;
    }
    case LSAType::MEAN:
    {
       LSAMean *ptr = new LSAMean();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    case LSAType::ENUO:
    {
       LSAEnuo *ptr = new LSAEnuo();
       ptr->fromString(line);
       recordPtr = dynamic_cast<LSARecord *>(ptr);
       break;
    }
    default:
    {
       return NULL;
    }
    }//end switch

    if (recordPtr->hasParseWarnings())
    {
        // If the record has parseWarnings to the following:
        // - push the warnings to the user
        // - do NOT insert the record into the LSATree
        // - return recordPtr for possible use by methods that call this method
        int numWarnings = recordPtr->parseWarnings.size();
        for (int i = 0; i < numWarnings; ++i)
        {
//dwt
            pushWarning(recordPtr->parseWarnings[i]);
        }
    }
    else
    {
        // If the record has no parse warnings, then insert it into the LSATree
        recordPtr->isCommented = recordIsCommented;
        parentIncludeRecord->insertNewRecord(position, recordPtr);
    }

    return recordPtr;
}

LSARecord* LSAFile::insertMapValue(LSAType type, std::string label, LSARecord* lsaRecord, bool recordIsCommented, bool parentIsActive)
{
    std::ostringstream warning_message;
    // If the record has parse warnings, don't add it to a map
    if (lsaRecord->hasParseWarnings()) return lsaRecord;

    // Don't insert labels for inactive records
    if (!parentIsActive || recordIsCommented)
    {
        if ( type == LSAType::DGRP)
        {
            LSADirGroupMap::iterator iter = dgrpMapComplete.find(label);
            if( iter == dgrpMapComplete.end())
            {
                LSADirGroup* lsaDirGroup = static_cast<LSADirGroup*>(lsaRecord);
                dgrpMapComplete.insert(std::pair<std::string, LSADirGroup*>(label, lsaDirGroup));
            }
            else
            {
                if(!applicationIsGui)
                {
                    warning_message << "Warning - duplicate DGRP label \"" << label << "\"\n";
                    pushWarning(warning_message.str());
                }
                return static_cast<LSARecord*>(iter->second);
            }
        }
       return NULL; // only add inactive records to dgrpMapComplete
    }

    if (type == LSAType::POSG || type == LSAType::POSC)
    {
        LSARecordMap::iterator iter = pointMap.find(label);
        if( iter == pointMap.end())
        {
            pointMap.insert(std::pair<std::string, LSARecord*>(label, lsaRecord));
        }
        else
        {
            if (!applicationIsGui)
            {
                warning_message << "Warning - duplicate Position label \"" << label << "\"\n";
                pushWarning(warning_message.str());
            }
            return iter->second;
        }
    }
    else if (type == LSAType::UNCR)
    {
        LSAUNCRMap::iterator iter = uncrMap.find(label);
        if( iter == uncrMap.end())
        {
            LSAUncertainty *lsaUncr = static_cast<LSAUncertainty*>(lsaRecord);
            uncrMap.insert(std::pair<std::string, LSAUncertainty*>(label, lsaUncr));
        }
        else
        {
            //duplicate UNCRs are allowed, if they have the same values - Fix to Bug #1293
            std::string thisLSAString = lsaRecord->getSingleLSAString();
            std::string storedLSAString = iter->second->getSingleLSAString();
            if(thisLSAString != storedLSAString)//distinct values
            {
                if (!applicationIsGui)
                {
                    warning_message << "Warning - duplicate UNCR label \"" << label << "\"\n";
                    pushWarning(warning_message.str());
                }
                return static_cast<LSARecord*>(iter->second);
            }
        }
    }
    else if (type == LSAType::VSCA)
    {
        LSAVSCAMap::iterator iter = vscaMap.find(label);
        if( iter == vscaMap.end())
        {
            LSAVarScaling* lsaVarPtr = static_cast<LSAVarScaling*>(lsaRecord);
            vscaMap.insert(std::pair<std::string, LSAVarScaling*>(label, lsaVarPtr));
        }
        else
        {
            if (!applicationIsGui)
            {
                warning_message << "Warning - duplicate VSCA label \"" << label << "\"\n";
                pushWarning(warning_message.str());
            }
            return static_cast<LSARecord*>(iter->second);
        }
    }
    else if (type == LSAType::HGHT)
    {
        LSAHGHTMap::iterator iter = hghtMap.find(label);
        if( iter == hghtMap.end())
        {
            LSAHeight* lsaHeight = static_cast<LSAHeight*>(lsaRecord);
            hghtMap.insert(std::pair<std::string, LSAHeight*>(label, lsaHeight));
        }
        else
        {
            if (!applicationIsGui)
            {
                warning_message << "Warning - duplicate HGHT label \"" << label << "\"\n";
                pushWarning(warning_message.str());
            }
            return static_cast<LSARecord*>(iter->second);
        }
    }
    else if (type == LSAType::DGRP)
    {
        LSADirGroupMap::iterator iter = dgrpMap.find(label);
        if( iter == dgrpMap.end())
        {
            LSADirGroup* lsaDirGroup = static_cast<LSADirGroup*>(lsaRecord);
            addDGRPpair(label, lsaDirGroup);
        }
        else
        {
            if (!applicationIsGui)
            {
                warning_message << "Warning - duplicate DGRP label \"" << label << "\"\n";
                pushWarning(warning_message.str());
            }
            return static_cast<LSARecord*>(iter->second);
        }
    }

    return NULL;
}

void LSAFile::addDGRPpair(const string &label, LSADirGroup *dgrp)
{
    if(label.empty())
    {
       return;
    }

    dgrpMap.insert(std::pair<std::string, LSADirGroup *>(label, dgrp));
    dgrpMapComplete.insert(std::pair<std::string, LSADirGroup *>(label, dgrp));
}

void LSAFile::removeDGRPLabel(const string &label)
{
    LSADirGroupMap::iterator it = dgrpMap.find(label);
    if(it != dgrpMap.end())
    {
        dgrpMap.erase(it);
    }

    it = dgrpMapComplete.find(label);
    if(it != dgrpMapComplete.end())
    {
        dgrpMapComplete.erase(it);
    }
}

void LSAFile::removeRecord(LSAInclude* parentInclude, int childNum)
{
    if (!parentInclude)
    {
        return;
    }
    if (childNum > parentInclude->childRecords.size())
    {
        return;
    }

    // Get the child record to delete
    LSARecord* childRecord = parentInclude->getChildRecord(childNum);

    // If the child record is an INCLUDE, remove it's filename from the set of files already included
    if (childRecord->getRecType() == LSAType::INCLUDE)
    {
        //recursively find all descendent INCLUDES
        // get the included filename
        LSAInclude* lsaInclude = static_cast<LSAInclude*>(childRecord);
        //workaround for Bug #1352
        QList<std::string> descendantIncludeAbsFilenames = getDescendantIncludes(lsaInclude);
        descendantIncludeAbsFilenames.append(lsaInclude->getAbsolutePath());

        // erase the filename from the set of included files
        std::set<std::string>::iterator it;
        foreach(std::string absFilename, descendantIncludeAbsFilenames)
        {
            it = includedLSAFiles.find(absFilename);
            if (it != includedLSAFiles.end())
            {
                includedLSAFiles.erase(it);
            }
        }
    }
    else if(childRecord->getRecType() == LSAType::POSG)
    {
        LSAPosG* lsaPosG = static_cast<LSAPosG*>(childRecord);
        LSARecordMap::iterator it;
        it = pointMap.find(lsaPosG->label);
        if(it != pointMap.end())
        {
            pointMap.erase(it);
        }
    }
    else if(childRecord->getRecType() == LSAType::POSC)
    {
        LSAPosC* lsaPosC = static_cast<LSAPosC*>(childRecord);
        LSARecordMap::iterator it;
        it = pointMap.find(lsaPosC->label);
        if(it != pointMap.end())
        {
            pointMap.erase(it);
        }
    }
    else if(childRecord->getRecType() == LSAType::DGRP)
    {
        LSADirGroup* lsaDirGroup = static_cast<LSADirGroup*>(childRecord);
        removeDGRPLabel(lsaDirGroup->label);
    }

    // Delete the child record in the lsa tree
    parentInclude->deleteChildRecord(childNum);

    return;

}

QList<std::string> LSAFile::getDescendantIncludes(LSAInclude* parentInclude)
{
    QList<std::string> includeAbsFilepaths;

    for (std::list<LSARecord*>::iterator it=parentInclude->childRecords.begin(); it != parentInclude->childRecords.end(); it++)
    {
        LSARecord* childRecord = *it;
        if(childRecord->getRecType() == LSAType::INCLUDE)
        {
            LSAInclude *childInclude = static_cast<LSAInclude*>(childRecord);
            includeAbsFilepaths.append(childInclude->getAbsolutePath());
            includeAbsFilepaths += getDescendantIncludes(childInclude);
        }
    }
    return includeAbsFilepaths;
}

