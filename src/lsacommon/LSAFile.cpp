// Create a DATAzimuth object and populate it with the data from this object
DATAzimuth LSAFile::convertToDAT(LSAAzimuth *lsaAzim, double groupVSCAFactor)
{
    double angleValue;
    if (lsaAzim->usesDecDeg)
    {
        if(::fabs(lsaAzim->angleDecDeg) < lsa::ZERO_BOUND)
            angleValue = 0.0;//convert -0.000000 to 0.000000
        else
            angleValue = lsaAzim->angleDecDeg;
    }
    else // in DMS
    {
       angleValue = DMSToDeg(lsaAzim->angleDMSIsNeg, lsaAzim->angleDeg, lsaAzim->angleMin, lsaAzim->angleSec);
    }

    if(upperCase(lsaAzim->fromDir) == string("S"))
    {
        angleValue += 180.0;
        if(angleValue > 360.0)
            angleValue -= 360.0;
    }

    std::string sigmaUnitsCopy(lsaAzim->sigmaUnits);
    gnsstk::StringUtils::upperCase(sigmaUnitsCopy);
    static const string RAD("rad");
    static const string DEG("deg");
    double angleRad = convertTo(RAD, angleValue, DEG);
    double sigmaRad = convertTo(RAD, lsaAzim->sigma, sigmaUnitsCopy);

    DATAzimuth datAzimuth(lsaAzim->From, lsaAzim->To, angleRad, sigmaRad);

    // Set From Height, and To height, and geoid correction
    LSAModifier *modifiers = &lsaAzim->modifiers;
    LSARecord   *lsaRecord = static_cast<LSARecord*>(lsaAzim);

    double fromHeight = getHeightFromInMeters(lsaRecord);
    double toHeight = getHeightToInMeters(lsaRecord);
    double fromHeightSigma = getHeightFromSigmaInMeters(lsaRecord);
    double toHeightSigma = getHeightToSigmaInMeters(lsaRecord);
    bool applyGeoidCorrections = !modifiers->isReducedToEllipsoid();
    datAzimuth.setCorrections(fromHeight, toHeight, fromHeightSigma, toHeightSigma, applyGeoidCorrections);

    // Uncr modifier
    datAzimuth.sigma = sqrt(pow(datAzimuth.sigma,2)+pow(getAddSigma(lsaRecord, RAD),2));

    double fromCenter = getFromCentError(lsaRecord);
    double toCenter   = getToCentError(lsaRecord);
    datAzimuth.setCenterSigmas(fromCenter, toCenter);

    // scaling
    double scalingFactor = getVSCAValue(lsaRecord) * groupVSCAFactor;
    datAzimuth.setScale(scalingFactor);

    return datAzimuth;
}

//------------------------------------------------------------------------------------
// Create a DATDelta object and populate it with the data from this object
DATDelta LSAFile::convertToDAT(LSADelta *lsaDelta, double groupVSCAFactor)
{
    static const string M("m");
    double fact = convertTo(M, 1.0, lsaDelta->linUnits);
    double fact2 = fact*fact;

    DATDelta datDelta(lsaDelta->From, lsaDelta->To, fact * lsaDelta->dx, fact * lsaDelta->dy, fact * lsaDelta->dz,
                      fact2 * lsaDelta->covxx, fact2 *  lsaDelta->covxy,
                      fact2 * lsaDelta->covxz, fact2 * lsaDelta->covyy,
                      fact2 * lsaDelta->covyz, fact2 * lsaDelta->covzz);

    LSAModifier *modifiers = &lsaDelta->modifiers;
    LSARecord   *lsaRecord = static_cast<LSARecord*>(lsaDelta);

    // Set From and To heights
    double fromHeight = getHeightFromInMeters(lsaRecord);
    double toHeight = getHeightToInMeters(lsaRecord);
    double fromHeightSigma = getHeightFromSigmaInMeters(lsaRecord);
    double toHeightSigma = getHeightToSigmaInMeters(lsaRecord);
    datDelta.setCorrections(fromHeight, toHeight, fromHeightSigma, toHeightSigma);

    // Additional sigma
    double sigma = getAddSigma(lsaRecord,M);
    double sigmaSquared = sigma * sigma;
    datDelta.covxx += sigmaSquared;
    datDelta.covyy += sigmaSquared;
    datDelta.covzz += sigmaSquared;

    // PPM sigma
    datDelta.setAddSigma(getPPMSigma(lsaRecord), true);

    // Centering errors
    double fromCenter = getFromCentError(lsaRecord);
    double toCenter   = getToCentError(lsaRecord);
    datDelta.setCenterSigmas(fromCenter, toCenter);

    // scaling
    double scalingFactor(1.0);
    scalingFactor *= groupVSCAFactor * getVSCAValue(lsaRecord);
    datDelta.setScale(scalingFactor);

    return datDelta;
}

//------------------------------------------------------------------------------------
// Create a DATDirSet object and populate it with the data from this object
// return DATDirSet object
DATDirSet LSAFile::convertToDAT(LSADirGroup *lsaDirGroup, double groupVSCAFactor)
{
    DATDirSet datDirSet(lsaDirGroup->label, lsaDirGroup->fromLabel);

    LSAModifier *modifiers = &lsaDirGroup->modifiers;
    LSARecord   *lsaRecord = static_cast<LSARecord*>(lsaDirGroup);

    // Geoid corrections
    bool applyGeoidCorrections = !modifiers->isReducedToEllipsoid();
    datDirSet.setCorrections(0.0, 0.0, applyGeoidCorrections);

    // At centering error
    bool hasAtCenteringError = hasAtCentError(lsaRecord);
    bool hasFromCenteringError = hasFromCentError(lsaRecord);
    if (hasFromCenteringError)
    {
        // if we found a FROM centering error, apply it
        double fromCenter = getFromCentError(lsaRecord);
        datDirSet.setCenterSigmas(fromCenter);
    }
    else if (hasAtCenteringError)
    {
        // if we have an AT error but no FROM error, use the AT error in place of the FROM error
        double atCenter = getAtCentError(lsaRecord);
        datDirSet.setCenterSigmas(atCenter);
    }

    // scaling
    double scalingFactor = getVSCAValue(lsaRecord) * groupVSCAFactor;
    datDirSet.setScale(scalingFactor);

    return datDirSet;
}


