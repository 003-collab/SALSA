//------------------------------------------------------------------------------------
// Create a DATPoint object and populate it with the data from this object
DATPoint LSAFile::convertToDAT(LSAPosC *lsaPosC, double groupVSCAFactor)
{
    // convert length units to meters
    static const string M("m");
    double fact = convertTo(M, 1.0, lsaPosC->posUnits);
    double fact2 = fact * fact;

    double xPos = fact*lsaPosC->x;
    double yPos = fact*lsaPosC->y;
    double zPos = fact*lsaPosC->z;

    double covXX = fact2 * lsaPosC->covxx;
    double covYY = fact2 * lsaPosC->covyy;
    double covZZ = fact2 * lsaPosC->covzz;
    double covXY = fact2 * lsaPosC->covxy;
    double covXZ = fact2 * lsaPosC->covxz;
    double covYZ = fact2 * lsaPosC->covyz;

    DATPoint datPoint(lsaPosC->label, xPos,  yPos,  zPos,
                            covXX, covXY, covXZ,
                            covYY, covYZ, covZZ);

    LSAModifier *modifiers = &lsaPosC->modifiers;
    LSARecord   *lsaRecord = static_cast<LSARecord*>(lsaPosC);

    // scaling
    double scalingFactor(1.0);
    if(modifiers->hasVSCACorrection())
        scalingFactor *= getVSCAValue(lsaRecord);
    if(groupVSCAFactor > 1.0e-9 && fabs(groupVSCAFactor-1.0) > 1.0e-9)
        scalingFactor *= groupVSCAFactor;
    datPoint.setScale(scalingFactor);

    DATPoint::Fixtype fixType;
    // Note: we have to check the isXXXFixed values first in this next if statement
    if (lsaPosC->fixedState == LSAFixedState::FIXED || (lsaPosC->isNorthFixed && lsaPosC->isEastFixed && lsaPosC->isUpFixed))
    {
        fixType = DATPoint::Fixtype::Fixed; // fixed
    }
    else if (lsaPosC->fixedState == LSAFixedState::FLOATING)
    {
        //0:unknown, 1:estimate, 2:fixed, 3:adjust
        fixType = DATPoint::Fixtype::Estimated; // estimate
    }
    else if (lsaPosC->fixedState == LSAFixedState::CONSTRAINED)
    {
        fixType = DATPoint::Fixtype::Adjusted; // adjust
    }

    datPoint.setFixType(fixType);

    std::string constraint;
    if (lsaPosC->isNorthFixed) constraint += "N";
    if (lsaPosC->isEastFixed) constraint += "E";
    if (lsaPosC->isUpFixed) constraint += "U";

    if (fixType != DATPoint::Fixtype::Fixed)
    {
        datPoint.setConstraintAxis(constraint);
    }
    else
    {
        datPoint.setConstraintAxis("");
    }

    return datPoint;

}


//------------------------------------------------------------------------------------
// Create a DATPoint object and populate it with the data from this object
DATPoint LSAFile::convertToDAT(LSAPosG *lsaPosG, bool &initialCall, double groupVSCAFactor)
{

    // TODO: Add tests for linear units, negative DD and DMS inputs

    // convert length units to meters
    static const string M("m");
    double fact = convertTo(M, 1.0, lsaPosG->heightUnits);
    double fact2 = fact*fact;

    double heightVal;
    try
    {
        if(!lsaPosG->heightIsEllipsoidal && validGeoidName)
        {
            if(initialCall)
            {
                allOrthoPos.clear();
                initialCall = false;
            }

            if(allOrthoPos.empty())
            {
                for(LSARecordMap::const_iterator pointMap_iter = pointMap.begin();
                    pointMap_iter != pointMap.end(); ++pointMap_iter)
                {
                    if(pointMap_iter->second->getRecType() == LSAType::Types::POSG)
                    {
                        LSAPosG *posgRecord = static_cast<LSAPosG *>(pointMap_iter->second);
                        if(!posgRecord->heightIsEllipsoidal)
                        {
                            allOrthoPos.push_back(posgRecord);
                        }
                    }
                }
                double latmin, latmax, lonmin, lonmax;
                FindBoundingBox(allOrthoPos, latmin, latmax, lonmin, lonmax);

                std::string rootIncludeName = getRootAbsolutePath();
                QString geoidPath;
                if(isProjectDirGeoid(rootIncludeName))
                {
                    geoidPath = QString::fromStdString(getPathWithoutFileName(rootIncludeName)+"/geoid/");
                }

                else
                {
                    geoidPath = QString::fromStdString(getExecutablePath() + string("/../data/geoid/"));
                }

                QString geoidName = getGeoidFileName(rootIncludeName);

                if(geoidName.isEmpty())
                {
                    validGeoidName = false;
                    std::ostringstream warningStream;
                    warningStream << "Warning - could not determine name of geoid file. Undulation values for orthometric records not found."
                                  << " Will treat all POSG heights as ellipsoidal.";
                    throw std::runtime_error(warningStream.str());
                }

                geoid = Geoid((geoidPath + geoidName).toStdString());// Find geoid file name
                geoid.setInterpolation("bicubic");
                geoid.loadGeoid(latmin, latmax, lonmin, lonmax);
                labelToUndMap = geoid.UpdateGeoidValues(allOrthoPos);
            }

            std::map<string, double>::const_iterator labelUndIter = labelToUndMap.find(lsaPosG->label);
            if(labelUndIter != labelToUndMap.end())
            {
                lsaPosG->initialUndulation = labelUndIter->second;
                heightVal = lsaPosG->height + (lsaPosG->initialUndulation/fact);
            }

            else
            {
                std::ostringstream warningStream;
                warningStream << "Warning - could not find undulation for orthometric record with label:\t" << lsaPosG->label;
                warningStream << ".\nHeight will be treated as ellipsoidal.";
                throw std::runtime_error(warningStream.str());
            }
        }

        else
        {
            heightVal = lsaPosG->height;
        }

    }

    catch(std::runtime_error &E)
    {
        pushWarning(E.what());
        heightVal = lsaPosG->height;
    }

    gnsstk::Position position(lsaPosG->giveStandardLat(), lsaPosG->giveStandardLon(), fact*heightVal, gnsstk::Position::Geodetic);

    // get ECEF xyz coordinates
    double xPos = position.getX();
    double yPos = position.getY();
    double zPos = position.getZ();

    // transform the covariance from NEU to ECEF
    // find the rotation matrix XYZ->NEU
    Matrix<double> rot = northEastUp(position);

    Matrix<double> covNEU(3,3);
    covNEU(0,0) = fact2 * lsaPosG->covnn;
    covNEU(1,1) = fact2 * lsaPosG->covee;
    covNEU(2,2) = fact2 * lsaPosG->covuu;
    covNEU(0,1) = covNEU(1,0) = fact2 * lsaPosG->covne;
    covNEU(0,2) = covNEU(2,0) = fact2 * lsaPosG->covnu;
    covNEU(1,2) = covNEU(2,1) = fact2 * lsaPosG->coveu;

    // NB since rot is XYZ->NEU, covXYZ = transpose(rot) * covNEU * rot
    Matrix<double> covXYZ = transpose(rot) * covNEU * rot;
    double covXX = covXYZ(0,0);
    double covYY = covXYZ(1,1);
    double covZZ = covXYZ(2,2);
    double covXY = covXYZ(0,1);
    double covXZ = covXYZ(0,2);
    double covYZ = covXYZ(1,2);

    DATPoint datPoint(lsaPosG->label, xPos,  yPos,  zPos,
                            covXX, covXY, covXZ,
                            covYY, covYZ, covZZ);

    LSAModifier *modifiers = &lsaPosG->modifiers;
    LSARecord   *lsaRecord = static_cast<LSARecord*>(lsaPosG);

    // scaling
    double scalingFactor(1.0);
    if(modifiers->hasVSCACorrection())
        scalingFactor *= getVSCAValue(lsaRecord);
    if(groupVSCAFactor > 1.0e-9 && fabs(groupVSCAFactor-1.0) > 1.0e-9)
        scalingFactor *= groupVSCAFactor;
    datPoint.setScale(scalingFactor);

    DATPoint::Fixtype fixType;
    // Note: we have to check the isXXXFixed values first in this next if statement
    if (lsaPosG->fixedState == LSAFixedState::FIXED || (lsaPosG->isNorthFixed && lsaPosG->isEastFixed && lsaPosG->isUpFixed))
    {
        fixType = DATPoint::Fixtype::Fixed; // fixed
    }
    else if (lsaPosG->fixedState == LSAFixedState::FLOATING)
    {
        //0:unknown, 1:estimate, 2:fixed, 3:adjust
        fixType = DATPoint::Fixtype::Estimated; // estimate
    }
    else if (lsaPosG->fixedState == LSAFixedState::CONSTRAINED)
    {
        fixType = DATPoint::Fixtype::Adjusted; // adjust
    }

    datPoint.setFixType(fixType);

    std::string constraint;
    if (lsaPosG->isNorthFixed) constraint += "N";
    if (lsaPosG->isEastFixed) constraint += "E";
    if (lsaPosG->isUpFixed) constraint += "U";

    if (fixType != DATPoint::Fixtype::Fixed)
    {
        datPoint.setConstraintAxis(constraint);
    }
    else
    {
        datPoint.setConstraintAxis("");
    }

    return datPoint;
}


