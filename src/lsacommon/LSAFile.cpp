//Much of this is duplicated in the convertToDat methods
//This code does not replace the convertToDat() calls to getAddSigma() because they don't all need a netSigma
//(e.g. DXYZ, HDIR, DGRP)
bool LSAFile::isValidSigma(LSARecord *lsaRecord) const
{
    static const string RAD("rad");
    static const string M("m");
    std::string sigmaUnitsCopy;
    double sigmaRad, netSigma=0.0;
    LSAType type = lsaRecord->getRecType();

    bool validSigma;

    // VIA Report on Bug 1263 only DIST DXYZ and HDIF records should be checked
    // for PPM

    if(type == LSAType::AZIM)
    {
        LSAAzimuth *lsaAzim = static_cast<LSAAzimuth*>(lsaRecord);
        sigmaUnitsCopy = lsaAzim->sigmaUnits;
        sigmaUnitsCopy = gnsstk::StringUtils::upperCase(sigmaUnitsCopy);
        sigmaRad = convertTo(RAD, lsaAzim->sigma, sigmaUnitsCopy);
        netSigma = sqrt(pow(sigmaRad,2)+pow(getAddSigma(lsaRecord, RAD),2));

        validSigma = netSigma > lsa::ZERO_BOUND || hasFromCentError(lsaRecord)
                      || hasToCentError(lsaRecord);
    }

    else if(type == LSAType::DXYZ)
    {
        LSADelta *lsaDelta = static_cast<LSADelta*>(lsaRecord);//assumes covariance matrix is in units of meters squared
        netSigma = sqrt(3*pow(getAddSigma(lsaRecord,M),2) + lsaDelta->covxx + lsaDelta->covyy + lsaDelta->covzz);

        validSigma = netSigma > lsa::ZERO_BOUND || hasFromCentError(lsaRecord)
                || hasToCentError(lsaRecord) || hasNonzeroPPMSigma(lsaRecord);
    }

    else if(type == LSAType::DIST)
    {
        LSADist *lsaDist = static_cast<LSADist*>(lsaRecord);
        double fact = convertTo(M, 1.0, lsaDist->linUnits);
        netSigma = sqrt(pow(fact * lsaDist->sigma,2)+pow(getAddSigma(lsaRecord, M),2));

        validSigma = netSigma > lsa::ZERO_BOUND || hasFromCentError(lsaRecord)
                || hasToCentError(lsaRecord) || hasNonzeroPPMSigma(lsaRecord);
    }

    else if(type == LSAType::HANG)
    {
        LSAHAngle *lsaHAngle = static_cast<LSAHAngle*>(lsaRecord);
        sigmaUnitsCopy = lsaHAngle->sigmaUnits;
        sigmaUnitsCopy = gnsstk::StringUtils::upperCase(sigmaUnitsCopy);
        sigmaRad = convertTo(RAD, lsaHAngle->sigma, sigmaUnitsCopy);
        netSigma = sqrt(pow(sigmaRad,2)+pow(getAddSigma(lsaRecord,RAD),2));

        validSigma = netSigma > lsa::ZERO_BOUND || hasAtCentError(lsaRecord)
                || hasFromCentError(lsaRecord) || hasToCentError(lsaRecord);
    }

    else if(type == LSAType::HDIR)
    {
        LSAHDir *lsaHDir = static_cast<LSAHDir*>(lsaRecord);
        double addSigma = 0.0;
        sigmaUnitsCopy = lsaHDir->sigmaUnits;
        sigmaUnitsCopy = gnsstk::StringUtils::upperCase(sigmaUnitsCopy);
        sigmaRad = convertTo(RAD, lsaHDir->sigma, sigmaUnitsCopy);
        // Find the direction group for this horiz direction
        if (dgrpMap.find(lsaHDir->dirGroupLabel) != dgrpMap.end())
        {
            LSADirGroup *dirGroup = dgrpMap.find(lsaHDir->dirGroupLabel)->second;
            addSigma = getAddSigma(static_cast<LSARecord*>(dirGroup),RAD);
        }
        netSigma = sqrt(pow(sigmaRad,2)+pow(addSigma,2));

        if(netSigma > lsa::ZERO_BOUND)
        {
            validSigma = true;
        }

        // Uncertainty record not directly associated with HDIR record.
        // Need to consult associated DGRP record.


        else if(dgrpMap.find(lsaHDir->dirGroupLabel) != dgrpMap.end())
        {
            LSADirGroup *dirGroup = dgrpMap.find(lsaHDir->dirGroupLabel)->second;
            validSigma = hasToCentError(static_cast<LSARecord*>(dirGroup))
                    || hasFromCentError(static_cast<LSARecord*>(dirGroup));
        }

        // If unable to find an associated DGRP record at this point, can't
        // associate a non-zero sigma component to HDIR record
        else
        {
            validSigma = false;
        }
    }

    else if(type == LSAType::HDIF)
    {
        LSAHeightDiff *lsaHDiff = static_cast<LSAHeightDiff*>(lsaRecord);
        double fact = convertTo(M, 1.0, lsaHDiff->linUnits);
        netSigma = sqrt(pow(fact * lsaHDiff->sigma,2)+pow(getAddSigma(lsaRecord,M),2));

        validSigma = netSigma > lsa::ZERO_BOUND || hasNonzeroPPMSigma(lsaRecord);
    }

    else if(type == LSAType::VANG)
    {
        LSAVAngle *lsaVAngle = static_cast<LSAVAngle*>(lsaRecord);
        sigmaUnitsCopy = lsaVAngle->sigmaUnits;
        sigmaUnitsCopy = gnsstk::StringUtils::upperCase(sigmaUnitsCopy);
        sigmaRad = convertTo(RAD, lsaVAngle->sigma, sigmaUnitsCopy);
        netSigma = sqrt(pow(sigmaRad,2)+pow(getAddSigma(lsaRecord,RAD),2));

        validSigma = netSigma > lsa::ZERO_BOUND || hasFromCentError(lsaRecord)
                || hasToCentError(lsaRecord);
    }
    else if(type == LSAType::ZANG)
    {
        LSAZAngle *lsaZAngle = static_cast<LSAZAngle*>(lsaRecord);
        sigmaUnitsCopy = lsaZAngle->sigmaUnits;
        sigmaUnitsCopy = gnsstk::StringUtils::upperCase(sigmaUnitsCopy);
        sigmaRad = convertTo(RAD, lsaZAngle->sigma, sigmaUnitsCopy);
        netSigma = sqrt(pow(sigmaRad,2)+pow(getAddSigma(lsaRecord,RAD),2));

        validSigma = netSigma > lsa::ZERO_BOUND || hasFromCentError(lsaRecord)
                || hasToCentError(lsaRecord);
    }

    else
    {
        validSigma = false;
    }

    return validSigma;
}

bool LSAFile::hasNonzeroPPMSigma(LSARecord *lsaRecord) const
{
    double ppmSigma = getPPMSigma(lsaRecord);
    if(ppmSigma > lsa::ZERO_BOUND)
        return true;
    else
        return false;
}

double LSAFile::getAddSigma(LSARecord *lsaRecord, const string& measUnits) const
{

    LSAModifier *modifiers = lsaRecord->getModifiers();
    if (modifiers == NULL) return 0.0;

    if ( !modifiers->hasUNCRCorrection() ) return 0.0;

    // Get the label for this model's uncertainty record
    std::string uncrLabel = modifiers->getUncrLabel();
    if ( uncrLabel.empty() ) return 0.0;

    // Get the uncertainty model
    if ( uncrMap.find(uncrLabel) == uncrMap.end() )
    {
        return 0.0;
    }
    LSAUncertainty *uncr = uncrMap.find(uncrLabel)->second;

    // Get the units for additional sigma
    std::string addSigmaUnits = uncr->sigmaUnits;
    upperCase(addSigmaUnits);


    if(isLinearUnit(addSigmaUnits) != isLinearUnit(measUnits))
    {
        return 0.0;
    }
    double fact=convertTo(measUnits,1.0,addSigmaUnits);

    return fact*uncr->Sigma;
}

string LSAFile::getAddSigmaUnits(LSARecord *lsaRecord) const
{

    LSAModifier *modifiers = lsaRecord->getModifiers();
    if (modifiers == NULL) return "";

    if ( !modifiers->hasUNCRCorrection() )
    {
        return string("");
    }

    std::string uncrLabel = modifiers->getUncrLabel();
    if ( uncrMap.find(uncrLabel) == uncrMap.end() )
    {
        return string("");
    }
    LSAUncertainty *uncr = uncrMap.find(uncrLabel)->second;

    if(!uncr->sigmaUnits.empty())
    {
        std::string sigmaUnitsCopy(uncr->sigmaUnits);
        return upperCase(sigmaUnitsCopy);
    }

    return string("");
}

