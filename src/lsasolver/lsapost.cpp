//------------------------------------------------------------------------------------
// Check input at the level of files exist? etc.
// Set bool GD.inputIsValid
int ValidateInput(void) throw(Exception)
{
try {
   int i,j;
   string msg;
   GlobalDataLsapost& GD=GlobalDataLsapost::Instance();
   GD.inputIsValid = true;

   if(GD.validate) {
      LOG(INFO) << " ---- Validate configuration ----";
   }

   // where else to do this?
   include_path(GD.logpath,GD.logfile);
   include_path(GD.binpath,GD.binfile);
   include_path(GD.datpath,GD.datfile);
   expand_filename(GD.logfile);
   expand_filename(GD.binfile);
   expand_filename(GD.datfile);

   if(GD.binfile.empty()) {
      msg = string("  Error - no input file.");
      LOG(ERROR) << msg;
      GD.inputIsValid = false;
   }

   if(!GD.configfile.empty())
   {
       include_path(GD.configpath,GD.configfile);
       expand_filename(GD.configfile);
       LOG(VERBOSE) << " Found solver .cfg file name " << GD.configfile;
   }

   if(!GD.outfile.empty())
   {
       include_path(GD.outpath,GD.outfile);
       expand_filename(GD.outfile);
       LOG(VERBOSE) << " Found solver .out file name " << GD.outfile;
   }

   if(!GD.hdf5file.empty())
   {
       include_path(GD.hdf5path,GD.hdf5file);
       expand_filename(GD.hdf5file);
       LOG(VERBOSE) << " Found lsapost .hf5 file name " << GD.hdf5file;
   }

   if(!GD.geoidfile.empty())
   {
      include_path(GD.geoidpath,GD.geoidfile);
      expand_filename(GD.geoidfile);
      //GD.LSAH5 = LSAH5File(GD.geoidfile);//need an explicit copy constructor to do it this way, needs descructor too
      //GD.LSAH5 = new LSAH5File(GD.geoidfile)//ned to make lsaH5 a pointer to do it this way, needs delete
      LOG(VERBOSE) << " Found geoid file name " << GD.geoidfile;
   }

   if(!GD.geoidfile2.empty())
   {
      include_path(GD.geoidpath,GD.geoidfile2);
      expand_filename(GD.geoidfile2);
      LOG(VERBOSE) << " Found second geoid file name " << GD.geoidfile2;
   }

   if(GD.validate) {
      LOG(INFO) << " ---- Input is "
         << (GD.inputIsValid ? "" : "NOT ") << "valid ----";
      return REQUESTED_VALIDATION;
   }

   if(GD.inputIsValid) return LSAPOST_OK;

   return INVALID_INPUT;
}
catch(Exception& e) { GNSSTK_RETHROW(e); }
}

//------------------------------------------------------------------------------------
int PreProcess(void) throw(Exception)
{
try {
   GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

   // open log file, if it exists
   if(!GD.logfile.empty()) {
      GD.oflog.open(GD.logfile.c_str(),ios_base::out);
      if(!GD.oflog.is_open()) {
         cerr << "Failed to open log file " << GD.logfile << endl;
         return OPEN_FAILURE;
      }
      LOG(INFO) << "Output directed to log file " << GD.logfile;
      pLOGstrm = &GD.oflog; // ConfigureLOG::Stream() = &GD.oflog;
   }

   // configure log stream
   ConfigureLOG::ReportLevels() = false;
   ConfigureLOG::ReportTimeTags() = false;
   // debug and verbose handled earlier in GetCommandLine/PreProcessArgs
   if(GD.debug > -1)
      ; // handled in CommandLine::PreProcessArgs()
   else if(GD.verbose)
      LOGlevel = ConfigureLOG::Level("VERBOSE");
   if(pLOGstrm != &cout) LOG(INFO) << GD.Title;

   // dump configuration
   if(GD.debug > -1) {
      LOG(INFO) << "Found debug switch at level " << GD.debug;
      LOG(INFO) << "\n" << GD.cmdlineUsage;  // this will contain list of args
      // NB debug turns on verbose
   }
   LOG(VERBOSE) << GD.cmdlineDump;

   return LSAPOST_OK;
}
catch(Exception& e) { GNSSTK_RETHROW(e); }
}

