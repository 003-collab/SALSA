Eigen::VectorXd DerivedPointMeanMappingFun(Eigen::VectorXd StateInputVect){

    // Bring in global data
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    // Output vector equal in length to the current state vector plus 3*number of fixed points that
    // are used for the mean calculation
    int InputDim = StateInputVect.size();
    // Output vector equal in length to the current state vector plus 3 for the mean derived point
    int OutputDim = GD.LSABin.StateNames.size()+3;
    Eigen::VectorXd MappedVector(OutputDim);
    MappedVector.setZero();

    int NumPtsToAvg = GD.IndicesForAveragedPtsForMean.size();

    // Initialize SumVect, for accumulating values from StateInputVect
    Eigen::VectorXd SumVect(3);
    SumVect.setZero();

    // Use GD.IndicesForAveragedPtsForMean to know what values to calculate mean for
    // Loop over indices in GD.IndicesForAveragedPtsForMean
    for(int ct=0; ct<NumPtsToAvg; ct++){
        SumVect(0) = SumVect(0) + StateInputVect(GD.IndicesForAveragedPtsForMean[ct]);
        SumVect(1) = SumVect(1) + StateInputVect(GD.IndicesForAveragedPtsForMean[ct]+1);
        SumVect(2) = SumVect(2) + StateInputVect(GD.IndicesForAveragedPtsForMean[ct]+2);
    }

    // Place current state vector in Mapped vector
    for(unsigned int ct=0; ct<GD.LSABin.StateNames.size(); ct++)
        MappedVector(ct) = StateInputVect(ct);

    // Place new mean derived point at the end of MappedVector
    MappedVector(GD.LSABin.StateNames.size()) = SumVect(0)/double(NumPtsToAvg);
    MappedVector(GD.LSABin.StateNames.size()+1) = SumVect(1)/double(NumPtsToAvg);
    MappedVector(GD.LSABin.StateNames.size()+2) = SumVect(2)/double(NumPtsToAvg);

    return MappedVector;
}

Eigen::MatrixXd MapMEANderPtCov(Eigen::MatrixXd AugCovariance, int StateDim){

    // Bring in global data
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    int InputDim = AugCovariance.cols();

    // input StateDim is the dimension of the state covariance without the augmented fixed points

    // Compute analytical partials to map the augmented covariance
    Eigen::MatrixXd Partials(StateDim+3,InputDim);
    Partials.setZero();

    // Set all of Partials associated directly with original state to identity
    for(int ct=0; ct<StateDim; ct++)
        Partials(ct,ct) = 1.0;

    // Set all partials of derived point wrt mean points
    int NumMeanPoints = GD.IndicesForAveragedPtsForMean.size();
    for(int ct=0; ct<NumMeanPoints; ct++){
        int MeanPtIndex = GD.IndicesForAveragedPtsForMean[ct];
        for(int i=0;i<3;i++){
            Partials(StateDim+i,MeanPtIndex+i) = 1.0/double(NumMeanPoints);
        }
    }

    // Employ analytical partials matrix to map the covariance
    Eigen::MatrixXd MappedCov = Partials * AugCovariance * Partials.transpose();
    return MappedCov;
}

bool createDerivedPointFromMEAN(std::string line, llhExternal & derivedLLH, xyzExternal & derivedXYZ) throw(Exception)
{
try
{

    // Bring in global data
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    // for removing numerical noise
    double eps = 1e-30;

    // The covariance is ECEF XYZ, not ENU
    int StateDim = GD.LSABin.Covariance.cols();

    // Updated covariance (with derived point added)
    Eigen::MatrixXd UpdatedCovEigen(StateDim+3,StateDim+3);
    UpdatedCovEigen.setZero();
    // Derived point ECEF XYZ position
    Eigen::VectorXd DerivedPtPos(3);
    // Derived point ECEF XYZ covariance (3x3)
    Eigen::MatrixXd DerivedPtCovXYZ(3,3);
    // Derived point NEU (not ENU, due to rotation matrix) covariance (3x3)
    Eigen::MatrixXd DerivedPtCovNEU(3,3);

    //-----------------------------------------------------------
    //
    // Parse the MEAN string
    //
    //-----------------------------------------------------------
    std::vector<std::string> fields = splitWithDoubleQuotes(line,' ');
    if (fields.size() < 5 )
    {
        std::cout << "Warning - MEAN record (" + line + ") has no input points." << std::endl;
        return false;
    }

    std::string linUnits = fields[3];
    if (linUnits != "m" && linUnits != "km" && linUnits != "ft"){
         std::cout << string("Warning - ENUO units must be m, km or ft.") << std::endl;
         return false;
    }
    static const string MEANU("M");
    double fact = convertTo(MEANU, 1.0, linUnits);

    // Covariance inflation term: the sigma value input is added as a squared quantity to the three
    // diagonal elements of the computed mean covariance
    double Sigma = ::atof(fields[2].c_str());
    Sigma = Sigma*fact;

    // new point label
    std::string newLabel = fields[1];

    // Create vector of strings containing input point names
    // The input points start at fields[4]
    std::vector<std::string> InputPointNames(fields.size()-4);
    for (int i = 4; i < fields.size(); ++i){
        InputPointNames[i-4] = fields[i];
    }

    // Initialize vector of fixed point positions, set length based on maximum possible
    // number of fixed points, which is the total number of input points (*3 for position
    // components)
    Eigen::VectorXd FixedPtPos(InputPointNames.size()*3);
    FixedPtPos.setZero();
    // Initializing count of fixed points
    int NumFixedPts = 0;

    // Extract state name vector
    std::vector<std::string> StateNameVect = GD.LSABin.StateNames.labels;

    // Initialize/resize vector of integers indicating x-component augmented vector indices of each point
    // in mean calculation (fixed and non-fixed) - used in DerivedPointMeanMappingFun
    GD.IndicesForAveragedPtsForMean.resize(InputPointNames.size());

    // Initialize iterator for extracting points from GD.Points
    map<string,Point>::iterator iterPoints;

    // Loop over all input points employed to compute the mean point
    for (int i = 0; i < InputPointNames.size(); ++i){
        std::string inputLabel = InputPointNames[i];
        iterPoints = GD.Points.find(inputLabel);
        // Confirm point is in GD.Points - all points should be there, including der pts
        // NOTE: any previously computed derived points are added to GD.Points, so derived points
        // can be one of the averaged points for a new mean derived point. Unused points are also
        // in GD.Points.
        // If point not in GD.Points, exit with warning
        if(iterPoints == GD.Points.end()){
            std::cout << string("Warning - input position (" + inputLabel + ") for MEAN record " + line + " not found.") << std::endl;
            return false;
        }
        // Search for the point in GD.LSABin.StateNames
        if(GD.LSABin.StateNames.contains(inputLabel+"X") == true){
            // if found in GD.LSABin.StateNames, then extract the x-component index for that point
            GD.IndicesForAveragedPtsForMean[i] = GD.LSABin.StateNames.index(inputLabel+"X");
        }
        // If point not in GD.LSABin.StateNames (i.e. list of states associated with the covariance),
        // then it's either fixed (most likely) or a float unused point (less likely). In either case,
        // the action is the same: extract the XYZ position, iterate the number of points that must
        // be added to the augmented state and covariance (specified as NumFixedPts, but also refers to
        // any unused float points), and save the associated index of that point in
        // GD.IndicesForAveragedPtsForMean for use when computing the mean position
        else{
            // Extract the fixed (or unused float) point position from GD.Points
            FixedPtPos(NumFixedPts*3) = iterPoints->second.x;
            FixedPtPos(NumFixedPts*3+1) = iterPoints->second.y;
            FixedPtPos(NumFixedPts*3+2) = iterPoints->second.z;
            // increment number of fixed (or unused float) points
            ++NumFixedPts;
            // Set GD.IndicesForAveragedPtsForMean[i] equal to the original covariance size (number of
            // estimated states) plus the number of fixed (or unused float) points determined so far
            // (accounting for having 3 position values for each fixed point)
            GD.IndicesForAveragedPtsForMean[i] = StateDim + 3*NumFixedPts-3;
        }
    }

    // Initialize augmented state vector containing fixed points
    Eigen::VectorXd AugStateInput(StateDim+NumFixedPts*3);
    AugStateInput.setZero();
    // Initialize augmented covariance containing fixed points
    Eigen::MatrixXd AugCovInput(StateDim+NumFixedPts*3,StateDim+NumFixedPts*3);
    AugCovInput.setZero();


    // Construct augmented state vector
    // All state values are extracted from GD.Points (including fixed)
    // Copy original state vector
    for(int i=0; i<StateDim; i++){
        std::string label = StateNameVect[i];
        // remove the x, y, or z value at the end
        std::string labelNoComp = label.substr(0,label.size()-1);
        // capture the x, y, or z value at the end
        std::string labelXYZcomp = label.substr(label.size()-1);

        // Find XYZ position component in GD.Points
        map<string,Point>::iterator iterXYZ = GD.Points.find(labelNoComp);
        // if labelNoComp found in GD.Points:
        if(iterXYZ != GD.Points.end()){
            Point fromPointXYZ = iterXYZ->second;
            if(labelXYZcomp == "X")
                AugStateInput(i) = fromPointXYZ.x;
            if(labelXYZcomp == "Y")
                AugStateInput(i) = fromPointXYZ.y;
            if(labelXYZcomp == "Z")
                AugStateInput(i) = fromPointXYZ.z;
        }
        // else this state is not relevant for derived points, so can be set to zero
        // (which is good, because these states do not appear to be accessible from GD)
        else {
            AugStateInput(i) = 0.0;
        }
    }
    // Then add fixed points
    for (int i = 0; i < NumFixedPts; ++i){
        AugStateInput(StateDim+i*3) = FixedPtPos(i*3);
        AugStateInput(StateDim+i*3+1) = FixedPtPos(i*3+1);
        AugStateInput(StateDim+i*3+2) = FixedPtPos(i*3+2);
    }

    // Construct augmented covariance
    // Copy original covariance
    for(int i=0; i<StateDim; i++)
        for(int j=0; j<StateDim; j++)
            AugCovInput(i,j) = GD.LSABin.Covariance(i,j);
    // All remaining components of augmented cov are zero - fixed points

    // Computing Mapped nominal state - use to create new derived point object
    Eigen::VectorXd MappedState = DerivedPointMeanMappingFun(AugStateInput);

    // Save derived point position
    DerivedPtPos(0) = MappedState(StateDim);
    DerivedPtPos(1) = MappedState(StateDim+1);
    DerivedPtPos(2) = MappedState(StateDim+2);



    // Map the covariance

    // Given the simple nature of the mean derived point, and the lengthy computation time required
    // by the sigma point transform when employed for adding derived points large projects (hundreds
    // of points), analytical partials are computed and employed to map the covariance for mean
    // derived points.  However, other kinds of derived points that may be desired in the future may
    // not have clean and easy analytical partials to compute (e.g. iterative methods).  Thus, the
    // code to employ sigma point transforms for derived points is retained here.
    bool EmploySigPtTransform = false;
    if(EmploySigPtTransform == true){
        // Employ Sigma Point Transform function to map the covariance
        UpdatedCovEigen = SigmaPointTransformFunc(AugStateInput,AugCovInput,DerivedPointMeanMappingFun);
    }
    else{
        // Employ analytical partials matrix to map the covariance
        UpdatedCovEigen = MapMEANderPtCov(AugCovInput,StateDim);
    }

    // Inflate derived point covariance by Sigma^2 (each diagonal element)
    UpdatedCovEigen(StateDim,StateDim) = UpdatedCovEigen(StateDim,StateDim) + ::pow(Sigma,2);
    UpdatedCovEigen(StateDim+1,StateDim+1) = UpdatedCovEigen(StateDim+1,StateDim+1) + ::pow(Sigma,2);
    UpdatedCovEigen(StateDim+2,StateDim+2) = UpdatedCovEigen(StateDim+2,StateDim+2) + ::pow(Sigma,2);

    // Save 3x3 cov associated with derived point
    for(int i=0; i<3; i++)
      for(int j=0; j<3; j++)
          DerivedPtCovXYZ(i,j) = UpdatedCovEigen(StateDim+i,StateDim+j);

    // Use gnsstk::Position to get ECEF2NEU rotation matrix
    gnsstk::Position toPosition(DerivedPtPos(0), DerivedPtPos(1), DerivedPtPos(2),
                               gnsstk::Position::Cartesian);
    gnsstk::Matrix<double> rot = northEastUpGeodetic(toPosition); //ECEF2NEU
    // convert to Eigen
    Eigen::MatrixXd ECEF2NEU(3,3);
    for(int i=0;i<3;i++)
        for(int j=0;j<3;j++)
            ECEF2NEU(i,j) = rot(i,j);

    // Rotate XYZ cov to NEU (not ENU unfortunately), for saving to points below
    DerivedPtCovNEU = ECEF2NEU * DerivedPtCovXYZ * ECEF2NEU.transpose();


    // Saving

    // Save new covariance to GD.LSABin.Covariance
    // Convert to gnsstk::Matrix<double>, for changing GD.LASBin.Covariance
    gnsstk::Matrix<double> UpdatedCov(StateDim+3,StateDim+3);
    for(int i=0; i<StateDim+3; i++)
        for(int j=0; j<StateDim+3; j++)
            UpdatedCov(i,j) = UpdatedCovEigen(i,j);
    // Not sure if this resize operation is necessary, but playing it safe
    GD.LSABin.Covariance.resize(StateDim+3,StateDim+3);
    GD.LSABin.Covariance = UpdatedCov;

    // Add derived point component state names to GD.LSABin.StateNames
    GD.LSABin.StateNames += newLabel + "X";
    GD.LSABin.StateNames += newLabel + "Y";
    GD.LSABin.StateNames += newLabel + "Z";

    // Fill in derivedXYZ and derivedLLH
    // Populate derivedXYZ
    derivedXYZ.label = newLabel;
    // xyz
    derivedXYZ.x = DerivedPtPos(0);
    derivedXYZ.y = DerivedPtPos(1);
    derivedXYZ.z = DerivedPtPos(2);
    // adjustments are not used for derived points
    derivedXYZ.adjX = derivedXYZ.adjY = derivedXYZ.adjZ = 0;
    // covariance
    derivedXYZ.Cxx = DerivedPtCovXYZ(0,0);
    derivedXYZ.Cxy = DerivedPtCovXYZ(0,1);
    derivedXYZ.Cxz = DerivedPtCovXYZ(0,2);
    derivedXYZ.Cyy = DerivedPtCovXYZ(1,1);
    derivedXYZ.Cyz = DerivedPtCovXYZ(1,2);
    derivedXYZ.Czz = DerivedPtCovXYZ(2,2);
    derivedXYZ.sigX = sqrt(derivedXYZ.Cxx);
    derivedXYZ.sigY = sqrt(derivedXYZ.Cyy);
    derivedXYZ.sigZ = sqrt(derivedXYZ.Czz);
    // flags
    derivedXYZ.sourceType  = DERIVED_MEAN;
    derivedXYZ.utilized = BOOL_TRUE;
    derivedXYZ.fixedType   = LSAFixedState::FLOATING;
    derivedXYZ.constraints  = ""; // not fixed in N, E, or U

    // Populate derivedLLH
    derivedLLH.label = newLabel;
    // Create new gnsstk::Position for Mean position, for computing lat/lon/ht, etc.
    gnsstk::Position toPos(derivedXYZ.x, derivedXYZ.y, derivedXYZ.z, gnsstk::Position::Cartesian);
    // lat, lon, ht
    derivedLLH.lat = toPos.getGeodeticLatitude();
    derivedLLH.lon = toPos.getLongitude();
    derivedLLH.ht  = toPos.getHeight();
    //oht, dovN, dovE
    if(GD.doGeoid){
        double und, dovN, dovE;
        if(GD.geoid.validPosition(toPos)){
            GD.geoid.calculateAll(toPos, und, dovN, dovE);
            derivedLLH.oht = derivedLLH.ht - und;
            derivedLLH.dovN = dovN;
            derivedLLH.dovE = dovE;
        }
        else{
            std::cout << "Warning - unable to update geoid values for derived station '" << derivedLLH.label << "'." << std::endl;
        }
    }
    else{
        derivedLLH.oht = derivedLLH.ht;
        derivedLLH.dovN = derivedLLH.dovE = 0.0;
    }
    // adjustments are not used for derived points
    derivedLLH.adjN = derivedLLH.adjE = derivedLLH.adjU = 0;
    // covariance
    derivedLLH.Cnn = DerivedPtCovNEU(0,0);
    derivedLLH.Cne = DerivedPtCovNEU(0,1);
    derivedLLH.Cnu = DerivedPtCovNEU(0,2);
    derivedLLH.Cee = DerivedPtCovNEU(1,1);
    derivedLLH.Ceu = DerivedPtCovNEU(1,2);
    derivedLLH.Cuu = DerivedPtCovNEU(2,2);
    derivedLLH.sigE = sqrt(derivedLLH.Cee);
    derivedLLH.sigN = sqrt(derivedLLH.Cnn);
    derivedLLH.sigU = sqrt(derivedLLH.Cuu);
    // ellipse data
    double maj3D, maj2D, min2D, azim, vert;
    getScaledConfidenceEllipse(GD.confstr, GD.LSABin.ndof,
                               derivedLLH.Cnn,derivedLLH.Cne,derivedLLH.Cnu,
                               derivedLLH.Cee,derivedLLH.Ceu,derivedLLH.Cuu,
                               maj3D, maj2D, min2D, azim, vert);
    derivedLLH.azim = azim;
    derivedLLH.maj3D = maj3D;
    derivedLLH.maj2D = maj2D;
    derivedLLH.min2D = min2D;
    derivedLLH.vert = vert;
    // flags
    derivedLLH.sourceType  = DERIVED_MEAN;
    derivedLLH.utilized = BOOL_TRUE;
    derivedLLH.fixedType   = LSAFixedState::FLOATING;
    derivedLLH.constraints  = ""; // not fixed in N, E, or U

    // Add to GD.Points
    // Create Point object
    Point DerivedPtPointObj;
    DerivedPtPointObj.label = newLabel;
    DerivedPtPointObj.x = DerivedPtPos(0);
    DerivedPtPointObj.y = DerivedPtPos(1);
    DerivedPtPointObj.z = DerivedPtPos(2);
    DerivedPtPointObj.covxx = DerivedPtCovXYZ(0,0);
    DerivedPtPointObj.covxy = DerivedPtCovXYZ(0,1);
    DerivedPtPointObj.covxz = DerivedPtCovXYZ(0,2);
    DerivedPtPointObj.covyy = DerivedPtCovXYZ(1,1);
    DerivedPtPointObj.covyz = DerivedPtCovXYZ(1,2);
    DerivedPtPointObj.covzz = DerivedPtCovXYZ(2,2);
    DerivedPtPointObj.und = derivedLLH.ht - derivedLLH.oht;
    DerivedPtPointObj.dovE = derivedLLH.dovE;
    DerivedPtPointObj.dovN = derivedLLH.dovN;
    // Add to GD.Points - not updating GD.Points2 until it's clear that it's needed
    // Also not updating GD.OrthoHts or OrthoHts2
    GD.Points.insert(map<std::string,Point>::value_type(newLabel,DerivedPtPointObj));

    return true;

}
catch(Exception& e) { GNSSTK_RETHROW(e); }
}

Eigen::VectorXd DerivedPointENUoffsetMappingFun(Eigen::VectorXd AugStateInputVect){
    // Bring in global data
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    int InputDim = AugStateInputVect.size();

    // Output vector same dimension as augmented input vector - last 3 values are
    // the derived point rather than the offset vector
    Eigen::VectorXd MappedVector(InputDim);
    MappedVector.setZero();

    // Loop over all states prior to offset vector
    for(int ct=0; ct<InputDim-3; ct++){
        MappedVector(ct) = AugStateInputVect(ct);
    }

    // Extract XYZ "From" state
    Eigen::VectorXd FromPos(3);
    for(int ct=0; ct<3; ct++){
        FromPos(ct) = AugStateInputVect(GD.ENUoffsetFromStateIndices[ct]);
    }

    // Use XYZ from position to compute XYZ to ENU rotation matrix
    // Unfortunately have to use GNSSTk objects
    gnsstk::Position fromPosition(FromPos(0), FromPos(1), FromPos(2), gnsstk::Position::Cartesian);
    // NOTE: this is the rotation from ECEF to NEU, not ENU (which would make more sense)
    // Unfortunately there is no EastNorthUpGeodetic function, as there should be
    gnsstk::Matrix<double> rot = northEastUpGeodetic(fromPosition); //ECEF2NEU

    // Convert back to Eigen
    Eigen::MatrixXd ECEF2NEU(3,3);
    for(int i=0;i<3;i++)
        for(int j=0;j<3;j++)
            ECEF2NEU(i,j) = rot(i,j);

    Eigen::MatrixXd NEU2ECEF = ECEF2NEU.transpose();

    // Extract ENU offset
    Eigen::VectorXd ENUoffset(3);
    for(int ct=0; ct<3; ct++){
        ENUoffset(ct) = AugStateInputVect(InputDim-3+ct);
    }
    // Convert to NEU offset (see above for why this is unfortunately necessary)
    Eigen::VectorXd NEUoffset(3);
    NEUoffset(0) = ENUoffset(1);
    NEUoffset(1) = ENUoffset(0);
    NEUoffset(2) = ENUoffset(2);

    // Rotate ENU offset to ECEF XYZ
    Eigen::VectorXd XYZoffset = NEU2ECEF * NEUoffset;

    // Add offset to "from" position to calculate derived point
    // Can't find the Eigen::seq method at all, no idea why
    // MappedVector(Eigen::seq(InputDim-3,InputDim-3+2)) = FromPos + XYZoffset;
    // this also doesn't work
    // MappedVector({InputDim,InputDim-3+1,InputDim-3+2}) = FromPos + XYZoffset;
    for(int ct=0; ct<3; ct++)
        MappedVector(InputDim-3+ct) = FromPos(ct) + XYZoffset(ct);

    return MappedVector;
}

Eigen::MatrixXd MapENUOderPtCov(Eigen::MatrixXd AugCovariance,Eigen::MatrixXd NEU2ECEF){

    // Bring in global data
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    int InputDim = AugCovariance.cols();

    int StateDim = InputDim - 3;

    // Rotate ENU offset vector cov to ECEF/XYZ
    Eigen::MatrixXd DerivedPtCovNEU(3,3);
    DerivedPtCovNEU.setZero();

    // Extract 3x3 derived point cov from bottom right of AugCovariance
    // Known that it is a diagonal matrix with sigma values for E,N,U
    // Must re-arrange E and N diagonal values to use NEU2ECEF
    DerivedPtCovNEU(0,0) = AugCovariance(StateDim+1,StateDim+1); // North
    DerivedPtCovNEU(1,1) = AugCovariance(StateDim,StateDim);     // East
    DerivedPtCovNEU(2,2) = AugCovariance(StateDim+2,StateDim+2); // Up

    Eigen::MatrixXd DerivedPtCovXYZ = NEU2ECEF * DerivedPtCovNEU * NEU2ECEF.transpose();

    // Copy 3x3 derived point offset vector cov to the bottom right of AugCovariance
    for(int i=0; i<3; i++)
      for(int j=0; j<3; j++)
          AugCovariance(i+StateDim,j+StateDim) = DerivedPtCovXYZ(i,j);

    // Compute analytical partials to map the augmented covariance
    Eigen::MatrixXd Partials(StateDim+3,StateDim+3);
    Partials.setZero();

    // Set all of Partials associated directly with original state to identity
    for(int ct=0; ct<StateDim; ct++)
        Partials(ct,ct) = 1.0;

    // Set partials of derived point wrt from point, using GD.ENUoffsetFromStateIndices
    for(int ct=0; ct<3; ct++)
        Partials(StateDim+ct,GD.ENUoffsetFromStateIndices[0]+ct) = 1.0;

    // Set partials of derived point wrt offset vector (identity since just adding to from point)
    for(int ct=0; ct<3; ct++)
        Partials(StateDim+ct,StateDim+ct) = 1.0;

    // Employ analytical partials matrix to map the covariance
    Eigen::MatrixXd MappedCov = Partials * AugCovariance * Partials.transpose();

    return MappedCov;
}

bool createDerivedPointFromENUO(std::string line, llhExternal & derivedLLH, xyzExternal & derivedXYZ) throw(Exception)
{
try
{
    // Bring in global data
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    // for removing numerical noise
    double eps = 1e-30;

    // The covariance is ECEF XYZ, not ENU
    int StateDim = GD.LSABin.Covariance.cols();

    //-----------------------------------------------------------
    //
    // Parse the ENUO string
    //
    //-----------------------------------------------------------
    std::vector<std::string> fields = splitWithDoubleQuotes(line,' ');
    if (fields.size() != 10){
        std::cout << string("Warning - ENUO record (" + line + ") should have 10 members.") << std::endl;
        return false;
    }

    std::string linUnits = gnsstk::StringUtils::lowerCase(fields[6]);
    if (linUnits != "m" && linUnits != "km" && linUnits != "ft"){
         std::cout << string("Warning - ENUO units must be m, km or ft.") << std::endl;
         return false;
    }

    static const string M("M");
    double fact = convertTo(M, 1.0, linUnits);

    std::string fromLabel = fields[1];
    std::string toLabel = fields[2];

    double deltaE = fact * asDouble(fields[3]);
    double deltaN = fact * asDouble(fields[4]);
    double deltaU = fact * asDouble(fields[5]);

    double sigmaE = fact * asDouble(fields[7]);
    double sigmaN = fact * asDouble(fields[8]);
    double sigmaU = fact * asDouble(fields[9]);

    //-----------------------------------------------------------
    //
    // Confirm "from" point exists
    //
    //-----------------------------------------------------------

    // NOTE: any previously computed derived points are added to GD.Points, so derived points
    // can be "from" points for other derived points.  Unused points are also in GD.Points.

    // Try to find from point in GD.Points
    map<string,Point>::iterator iterPoints = GD.Points.find(fromLabel);
    // If it's not in GD.Points:
    if(iterPoints == GD.Points.end())
    {
        std::cout << string("Warning - input position (" + fromLabel + ") for ENUO record " + toLabel + " not found.") << std::endl;
        return false;
    }


    // objects used for both "from point" scenarios: fixed (used and unused) points and
    // adjusted/derived points

    // Updated covariance (with derived point added)
    Eigen::MatrixXd UpdatedCovEigen(StateDim+3,StateDim+3);
    UpdatedCovEigen.setZero();
    // Derived point ECEF XYZ position
    Eigen::VectorXd DerivedPtPos(3);
    // Derived point ECEF XYZ covariance (3x3)
    Eigen::MatrixXd DerivedPtCovXYZ(3,3);
    // Derived point NEU (not ENU, due to rotation matrix) covariance (3x3)
    Eigen::MatrixXd DerivedPtCovNEU(3,3);

    // ECEF-XYZ to NEU rotation matrix
    // Extract "from" Point object
    Point pt(iterPoints->second);
    // use from position to compute XYZ to NEU (not ENU) rotation matrix
    gnsstk::Position fromPosition(pt.x, pt.y, pt.z, gnsstk::Position::Cartesian);
    gnsstk::Matrix<double> rot = northEastUpGeodetic(fromPosition); //ECEF2NEU
    // convert to Eigen
    Eigen::MatrixXd ECEF2NEU(3,3);
    for(int i=0;i<3;i++)
        for(int j=0;j<3;j++)
            ECEF2NEU(i,j) = rot(i,j);
    Eigen::MatrixXd NEU2ECEF = ECEF2NEU.transpose();

    // Search for the point in GD.LSABin.StateNames
    bool InStateNames = GD.LSABin.StateNames.contains(fromLabel+"X");

    // If it's not found in GD.LSABin.StateNames (i.e. list of states associated with the covariance),
    // then it's either fixed (used or unused) (most likely) or a float unused point (less likely).
    // Fixed (or unused float) point position values are included in GD.Points above, so they can still
    // be used as "from" points.

    // Note: Any unused points that are provided a priori covs ("constrained") are placed in the
    // solution vector and covariance by SALSA (and so will be found within GD.LSABin.StateNames), so
    // those will be treated as adjusted "from" points.

    // Note: fixed used points are included in GD.LSABin.posXYZResults (where cov values will be
    // zero), but not in GD.LSABin.Covariance. So checking GD.LSABin.posXYZResults does not
    // determine if a point is fixed or not, and thus excluded or not from GD.LSABin.Covariance.

    // If not in GD.LSABin.StateNames:
    if(InStateNames != true){
        // For fixed (or unused float) from points, derived point position and cov is easily computed
        // without sigma point transform

        // rotate ENU offset vector to ECEF/XYZ
        Eigen::VectorXd NEUoffset(3);
        NEUoffset(0) = deltaN;
        NEUoffset(1) = deltaE;
        NEUoffset(2) = deltaU;
        // Rotate ENU offset to ECEF XYZ
        Eigen::VectorXd XYZoffset = NEU2ECEF * NEUoffset;
        // Add offset to unused point position
        DerivedPtPos(0) = pt.x + XYZoffset(0);
        DerivedPtPos(1) = pt.y + XYZoffset(1);
        DerivedPtPos(2) = pt.z + XYZoffset(2);

        // Rotate ENU cov to ECEF/XYZ
        DerivedPtCovNEU.setZero();
        DerivedPtCovNEU(0,0) = pow(sigmaN,2);
        DerivedPtCovNEU(1,1) = pow(sigmaE,2);
        DerivedPtCovNEU(2,2) = pow(sigmaU,2);
        DerivedPtCovXYZ = NEU2ECEF * DerivedPtCovNEU * NEU2ECEF.transpose();

        // Copy over the values associated with the original covariance
        for(int i=0; i<StateDim; i++)
          for(int j=0; j<StateDim; j++)
              UpdatedCovEigen(i,j) = GD.LSABin.Covariance(i,j);
        // Copy 3x3 derived point cov to the bottom right
        for(int i=0; i<3; i++)
          for(int j=0; j<3; j++)
              UpdatedCovEigen(i+StateDim,j+StateDim) = DerivedPtCovXYZ(i,j);

    }
    // otherwise the "from" point is an adjusted or previous derived point that is part of
    // the GD.LSABin.Covariance matrix, so must map full covariance to obtain all cross-cov terms
    else {

        //-----------------------------------------------------------
        //
        // Assemble augmented vector containing ENU offset, and augmented covariance
        // containing ENU offset uncertainty
        //
        //-----------------------------------------------------------

        // Extract XYZ state vector, given StateNames, place in augmented state vector
        Eigen::VectorXd AugStateInputVect(StateDim+3);
        AugStateInputVect.setZero();
        std::vector<std::string> StateNameVect = GD.LSABin.StateNames.labels;
        for(int i=0; i<StateDim; i++){
            std::string label = StateNameVect[i];
            // remove the x, y, or z value at the end
            std::string labelNoComp = label.substr(0,label.size()-1);
            // capture the x, y, or z value at the end
            std::string labelXYZcomp = label.substr(label.size()-1);

            // Determine the indices of the "from" point, save in GD for use in mapping function
            // DerivedPointENUoffsetMappingFun
            // If this label is the "from" point, then set "from" index vector accordingly
            if(labelNoComp == fromLabel){
                if(labelXYZcomp == "X")
                    GD.ENUoffsetFromStateIndices[0] = i;
                if(labelXYZcomp == "Y")
                    GD.ENUoffsetFromStateIndices[1] = i;
                if(labelXYZcomp == "Z")
                    GD.ENUoffsetFromStateIndices[2] = i;
            }

            // Find XYZ position component in GD.Points
            map<string,Point>::iterator iterXYZ = GD.Points.find(labelNoComp);
            // if labelNoComp found in GD.Points:
            if(iterXYZ != GD.Points.end()){
                Point fromPointXYZ = iterXYZ->second;
                if(labelXYZcomp == "X")
                    AugStateInputVect(i) = fromPointXYZ.x;
                if(labelXYZcomp == "Y")
                    AugStateInputVect(i) = fromPointXYZ.y;
                if(labelXYZcomp == "Z")
                    AugStateInputVect(i) = fromPointXYZ.z;
            }
            // else this state is not relevant for derived points, so can be set to zero
            // (which is good, because these states do not appear to be accessible from GD)
            else {
                AugStateInputVect(i) = 0.0;
            }
        }

        // Add offset vector to augmented vector
        AugStateInputVect(StateDim) = deltaE;
        AugStateInputVect(StateDim+1) = deltaN;
        AugStateInputVect(StateDim+2) = deltaU;

        // Construct augmented covariance, containing the original state cov and the offset vector
        // uncertainties
        Eigen::MatrixXd AugCovariance(StateDim+3,StateDim+3);
        AugCovariance.setZero();
        for(int i=0; i<StateDim; i++){
            for(int j=0; j<StateDim; j++){
                AugCovariance(i,j) = GD.LSABin.Covariance(i,j);
            }
        }
        // Add offset vector uncertainties to augmented covariance
        AugCovariance(StateDim,StateDim) = pow(sigmaE,2);
        AugCovariance(StateDim+1,StateDim+1) = pow(sigmaN,2);
        AugCovariance(StateDim+2,StateDim+2) = pow(sigmaU,2);

        // Computing Mapped nominal state - use to create new derived point object
        Eigen::VectorXd MappedState = DerivedPointENUoffsetMappingFun(AugStateInputVect);

        // Save derived point position
        DerivedPtPos(0) = MappedState(StateDim);
        DerivedPtPos(1) = MappedState(StateDim+1);
        DerivedPtPos(2) = MappedState(StateDim+2);

        // Map the covariance

        // Given the simple nature of the offset derived point, and the lengthy computation time required
        // by the sigma point transform when employed for adding derived points large projects (hundreds
        // of points), analytical partials are computed and employed to map the covariance for offset
        // derived points.  However, other kinds of derived points that may be desired in the future may
        // not have clean and easy analytical partials to compute (e.g. iterative methods).  Thus, the
        // code to employ sigma point transforms for derived points is retained here.
        bool EmploySigPtTransform = false;
        if(EmploySigPtTransform == true){
            // Employ Sigma Point Transform function to map the covariance
            UpdatedCovEigen = SigmaPointTransformFunc(AugStateInputVect,AugCovariance,DerivedPointENUoffsetMappingFun);
        }
        else{
            // Employ analytical partials matrix to map the covariance
            UpdatedCovEigen = MapENUOderPtCov(AugCovariance,NEU2ECEF);
        }

        // Save 3x3 cov associated with derived point
        for(int i=0; i<3; i++)
          for(int j=0; j<3; j++)
              DerivedPtCovXYZ(i,j) = UpdatedCovEigen(StateDim+i,StateDim+j);

        // Rotate XYZ cov to NEU (not ENU unfortunately), for saving to points below
        DerivedPtCovNEU = ECEF2NEU * DerivedPtCovXYZ * ECEF2NEU.transpose();
    }

    // Save new covariance to GD.LSABin.Covariance
    // Convert to gnsstk::Matrix<double>, for changing GD.LASBin.Covariance
    gnsstk::Matrix<double> UpdatedCov(StateDim+3,StateDim+3);
    for(int i=0; i<StateDim+3; i++)
        for(int j=0; j<StateDim+3; j++)
            UpdatedCov(i,j) = UpdatedCovEigen(i,j);
    // Not sure if this resize operation is necessary, but playing it safe
    GD.LSABin.Covariance.resize(StateDim+3,StateDim+3);
    GD.LSABin.Covariance = UpdatedCov;

    // Add derived point component state names to GD.LSABin.StateNames
    GD.LSABin.StateNames += toLabel + "X";
    GD.LSABin.StateNames += toLabel + "Y";
    GD.LSABin.StateNames += toLabel + "Z";

    // Fill in derivedXYZ and derivedLLH
    // Populate derivedXYZ
    derivedXYZ.label = toLabel;
    // xyz
    derivedXYZ.x = DerivedPtPos(0);
    derivedXYZ.y = DerivedPtPos(1);
    derivedXYZ.z = DerivedPtPos(2);
    // adjustments are not used for derived points
    derivedXYZ.adjX = derivedXYZ.adjY = derivedXYZ.adjZ = 0;
    // covariance
    derivedXYZ.Cxx = DerivedPtCovXYZ(0,0);
    derivedXYZ.Cxy = DerivedPtCovXYZ(0,1);
    derivedXYZ.Cxz = DerivedPtCovXYZ(0,2);
    derivedXYZ.Cyy = DerivedPtCovXYZ(1,1);
    derivedXYZ.Cyz = DerivedPtCovXYZ(1,2);
    derivedXYZ.Czz = DerivedPtCovXYZ(2,2);
    derivedXYZ.sigX = sqrt(derivedXYZ.Cxx);
    derivedXYZ.sigY = sqrt(derivedXYZ.Cyy);
    derivedXYZ.sigZ = sqrt(derivedXYZ.Czz);
    // flags
    derivedXYZ.sourceType  = DERIVED_ENUO;
    derivedXYZ.utilized = BOOL_TRUE;
    derivedXYZ.fixedType   = LSAFixedState::FLOATING;
    derivedXYZ.constraints  = ""; // not fixed in N, E, or U

    // Populate derivedLLH
    derivedLLH.label = toLabel;
    // Create new gnsstk::Position for To position, for computing lat/lon/ht, etc.
    gnsstk::Position toPos(derivedXYZ.x, derivedXYZ.y, derivedXYZ.z, gnsstk::Position::Cartesian);
    // lat, lon, ht
    derivedLLH.lat = toPos.getGeodeticLatitude();
    derivedLLH.lon = toPos.getLongitude();
    derivedLLH.ht  = toPos.getHeight();
    //oht, dovN, dovE
    if(GD.doGeoid){
        double und, dovN, dovE;
        if(GD.geoid.validPosition(toPos)){
            GD.geoid.calculateAll(toPos, und, dovN, dovE);
            derivedLLH.oht = derivedLLH.ht - und;
            derivedLLH.dovN = dovN;
            derivedLLH.dovE = dovE;
        }
        else{
            std::cout << "Warning - unable to update geoid values for derived station '" << derivedLLH.label << "'." << std::endl;
        }
    }
    else{
        derivedLLH.oht = derivedLLH.ht;
        derivedLLH.dovN = derivedLLH.dovE = 0.0;
    }
    // adjustments are not used for derived points
    derivedLLH.adjN = derivedLLH.adjE = derivedLLH.adjU = 0;
    // covariance
    derivedLLH.Cnn = DerivedPtCovNEU(0,0);
    derivedLLH.Cne = DerivedPtCovNEU(0,1);
    derivedLLH.Cnu = DerivedPtCovNEU(0,2);
    derivedLLH.Cee = DerivedPtCovNEU(1,1);
    derivedLLH.Ceu = DerivedPtCovNEU(1,2);
    derivedLLH.Cuu = DerivedPtCovNEU(2,2);
    derivedLLH.sigE = sqrt(derivedLLH.Cee);
    derivedLLH.sigN = sqrt(derivedLLH.Cnn);
    derivedLLH.sigU = sqrt(derivedLLH.Cuu);
    // ellipse data
    double maj3D, maj2D, min2D, azim, vert;
    getScaledConfidenceEllipse(GD.confstr, GD.LSABin.ndof,
                               derivedLLH.Cnn,derivedLLH.Cne,derivedLLH.Cnu,
                               derivedLLH.Cee,derivedLLH.Ceu,derivedLLH.Cuu,
                               maj3D, maj2D, min2D, azim, vert);
    derivedLLH.azim = azim;
    derivedLLH.maj3D = maj3D;
    derivedLLH.maj2D = maj2D;
    derivedLLH.min2D = min2D;
    derivedLLH.vert = vert;
    // flags
    derivedLLH.sourceType  = DERIVED_ENUO;
    derivedLLH.utilized = BOOL_TRUE;
    derivedLLH.fixedType   = LSAFixedState::FLOATING;
    derivedLLH.constraints  = ""; // not fixed in N, E, or U

    // Add to GD.Points
    // Create Point object
    Point DerivedPtPointObj;
    DerivedPtPointObj.label = toLabel;
    DerivedPtPointObj.x = DerivedPtPos(0);
    DerivedPtPointObj.y = DerivedPtPos(1);
    DerivedPtPointObj.z = DerivedPtPos(2);
    DerivedPtPointObj.covxx = DerivedPtCovXYZ(0,0);
    DerivedPtPointObj.covxy = DerivedPtCovXYZ(0,1);
    DerivedPtPointObj.covxz = DerivedPtCovXYZ(0,2);
    DerivedPtPointObj.covyy = DerivedPtCovXYZ(1,1);
    DerivedPtPointObj.covyz = DerivedPtCovXYZ(1,2);
    DerivedPtPointObj.covzz = DerivedPtCovXYZ(2,2);
    DerivedPtPointObj.und = derivedLLH.ht - derivedLLH.oht;
    DerivedPtPointObj.dovE = derivedLLH.dovE;
    DerivedPtPointObj.dovN = derivedLLH.dovN;
    // Add to GD.Points - not updating GD.Points2 until it's clear that it's needed
    // Also not updating GD.OrthoHts or OrthoHts2
    GD.Points.insert(map<std::string,Point>::value_type(toLabel,DerivedPtPointObj));

    return true;

}
catch(Exception& e)
    {
        GNSSTK_RETHROW(e);
    }
}

//------------------------------------------------------------------------------------
void fillMeasurementsStruct() throw(Exception)
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();
    bool blunder_exists=false;
    double lowest_redundancy=9999999.9;

    try
    {
        if(GD.LSABin.dataResults.size()>0)
        {
            map<string,data_result>::iterator it;
            for(it=GD.LSABin.dataResults.begin(); it!=GD.LSABin.dataResults.end(); ++it)
            {
                string label(it->first);
                data_result adjmeas(it->second);

                int firstParenIndex = label.find(string("("));
                int secondParenIndex = label.find(string(")"));
                int firstDotIndex = label.find(string("."));
                string meas = label.substr(0,firstDotIndex);
                string ID = label.substr(firstDotIndex+2,firstParenIndex-firstDotIndex-2);
                string from(""), at(""), to("");
                double conversion_factor = 1.0;
                if(meas == string("Del"))
                {
                    meas = string("DXYZ.") + label.substr(secondParenIndex+1);
                }
                else if(meas == string("Dir"))
                {
                    conversion_factor = 180.0*3600.0/Pi;
                    meas = string("HDIR");
                }
                else if(meas == string("Dis"))
                    meas = string("DIST");
                else if(meas == string("Zan"))
                {
                    conversion_factor = 180.0*3600.0/Pi;
                    meas = string("ZANG");
                }
                else if(meas == string("Van"))
                {
                    conversion_factor = 180.0*3600.0/Pi;
                    meas = string("VANG");
                }
                else if(meas == string("Azm"))
                {
                    conversion_factor = 180.0*3600.0/Pi;
                    meas = string("AZIM");
                }
                else if(meas == string("Han"))
                {
                    conversion_factor = 180.0*3600.0/Pi;
                    meas = string("HANG");
                }
                else if(meas == string("Hgt"))
                    meas = string("HDIF");
                else if(meas == string("PsPos"))
                    meas = string("PPP.") + label.substr(secondParenIndex+1);

                getFromAtToWithTag(ID,from,at,to);

                double initial_meas = adjmeas.meas*conversion_factor;
                double adjusted_meas = adjmeas.nomin*conversion_factor;
                double raw_resid = std::fabs(adjusted_meas - initial_meas);
                bool is_blunder(adjmeas.PossibleOutlier);
                bool redundancy_zero = adjmeas.RedundancyZero;
                GD.LSAH5.measurements->addDataPoint(meas, from, to, ID, initial_meas, adjusted_meas,
                                                                    raw_resid, adjmeas.resid, adjmeas.stdresid, adjmeas.redundancy,
                                                                    adjmeas.minDectBias, adjmeas.extVectMag,
                                                                    is_blunder, redundancy_zero, false, at);
                if(adjmeas.redundancy < lowest_redundancy)
                    lowest_redundancy = adjmeas.redundancy;
                if(is_blunder)
                    blunder_exists = true;
            }//and of for loop over dataResults

            GD.LSAH5.blundersExist->addDataPoint(blunder_exists);
            GD.LSAH5.lowestRedundancy->addDataPoint(lowest_redundancy);
        }//end of if on dataResults.size()>0
        else
        {
            //store initial measurements? Don't think we want those.
        }

        //handle derived measurements -- None yet.  Possibly TBD with Requirement096.
    }
    catch(Exception& e) { GNSSTK_RETHROW(e); }
}

