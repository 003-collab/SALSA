void getScaledConfidenceEllipse(std::string confidence, int ndof, double Cnn, double Cne, double Cnu,
                                double Cee, double Ceu, double Cuu, double& maj3D, double& maj2D, double& min2D,
                                double& azim, double& vert)
{
    double scaleFactor_1d = getConfidenceFactor(confidence,1,ndof);
    double scaleFactor_2d = getConfidenceFactor(confidence,2,ndof);
    double scaleFactor_3d = getConfidenceFactor(confidence,3,ndof);

    gnsstk::Matrix<double> Cov(3,3);

    Cov(0,0) = Cnn;
    Cov(0,1) = Cne;
    Cov(0,2) = Cnu;
    Cov(1,0) = Cne;
    Cov(1,1) = Cee;
    Cov(1,2) = Ceu;
    Cov(2,0) = Cnu;
    Cov(2,1) = Ceu;
    Cov(2,2) = Cuu;

    double maj3, min3, maj2, min2, ver, azm;
    getEllipse(Cov,maj3,min3,maj2,min2,ver,azm);

    maj3D = maj3 * scaleFactor_3d;
    maj2D = maj2 * scaleFactor_2d;
    min2D = min2 * scaleFactor_2d;
    azim = azm;
    vert = ver * scaleFactor_1d;
}

