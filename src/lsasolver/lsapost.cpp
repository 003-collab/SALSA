void fillSolCovarStruct() throw(Exception)
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();
    size_t i, j, n, jlast;

    try
    {
        //copied from LSABin::DumpCovariance
        Matrix<double> Cov(GD.LSABin.Covariance);
        LabeledMatrix LM(GD.LSABin.StateNames,Cov);

        //copied from gnsstk/src/core/lib/Geomatics/Namelist.cpp -- ostream& operator<<(ostream& os, const LabeledMatrix& LM)
        const Namelist *pNLcol = &LM.NLcols;
        const Namelist *pNLrow = &LM.NLrows;
        if(LM.NLrows.size() == 0 && LM.NLcols.size() == 0)
            return;//matrix is empty!
        if(LM.NLrows.size() == 0) pNLrow = pNLcol;
        if(LM.NLcols.size() == 0) pNLcol = pNLrow;
        n = (LM.M.cols() < pNLcol->size() ? LM.M.cols() : pNLcol->size());
        //add column/row labels (same order for each)
        for(i=0; i<n; i++)
            GD.LSAH5.solutionCovariance->addAxisLabel(pNLcol->getName(i));
        //add covariances
        for(i=0; i<LM.M.rows(); i++)//loop over rows
        {
            vector<double> row;
            row.clear();
            jlast = (LM.sym ? i+1 : LM.M.cols());//loop over columns
            for(j=0; j<jlast; j++)
                row.push_back(LM.M(i,j));
            GD.LSAH5.solutionCovariance->addRowToMatrix(row);
        }
    }
    catch(Exception& e) { GNSSTK_RETHROW(e); }
}

