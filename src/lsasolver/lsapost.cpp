void getFromAtToWithTag(string ID, string& from, string& at, string& to)
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    for(int i=0;i<GD.Records.size();i++)
    {
        if(GD.Records[i]->getTag() == (string("T")+ID))
        {
            DATtype type = GD.Records[i]->getRecType();
            if(type == DATtype::AZM)
            {
                DATAzimuth *datAzimuth = static_cast<DATAzimuth *>(GD.Records[i]);
                from = datAzimuth->From;
                to = datAzimuth->To;
                break;
            }
            else if(type == DATtype::DEL)
            {
                DATDelta *datDelta = static_cast<DATDelta *>(GD.Records[i]);
                from = datDelta->From;
                to = datDelta->To;
                break;
            }
            else if(type == DATtype::DIR)
            {
                DATDir *datDir = static_cast<DATDir *>(GD.Records[i]);
                to = datDir->To;
                std::string DirSetLabel = datDir->DSGroup;
                for(int j=0;j<GD.Records.size();j++)
                {
                    if(GD.Records[j]->getRecType() == DATtype::DIRSET)
                    {
                        DATDirSet *datDirSet = static_cast<DATDirSet *>(GD.Records[j]);
                        if(datDirSet->DSGroup == DirSetLabel)
                        {
                            from = datDirSet->From;
                            break;
                        }
                    }
                }
                break;
            }
            else if(type == DATtype::DIRSET)
            {
                DATDirSet *datDirset = static_cast<DATDirSet *>(GD.Records[i]);
                from = datDirset->From;
                break;
            }
            else if(type == DATtype::DIS)
            {
                DATDist *datDist = static_cast<DATDist *>(GD.Records[i]);
                from = datDist->From;
                to = datDist->To;
                break;
            }
            else if(type == DATtype::HAN)
            {
                DATHAngle *datHangle = static_cast<DATHAngle *>(GD.Records[i]);
                from = datHangle->From;
                to = datHangle->To;
                at = datHangle->At;
                break;
            }
            else if(type == DATtype::HGT)
            {
                DATHeight *datHeight = static_cast<DATHeight *>(GD.Records[i]);
                from = datHeight->From;
                to = datHeight->To;
                break;
            }
            else if(type == DATtype::POS)
            {
                DATPoint *datPoint = static_cast<DATPoint *>(GD.Records[i]);
                at = datPoint->label;//GUI resid table has in FromAt column
                break;
            }
            else if(type == DATtype::VAN)
            {
                DATVAngle *datVangle = static_cast<DATVAngle *>(GD.Records[i]);
                from = datVangle->From;
                to = datVangle->To;
                break;
            }
            else if(type == DATtype::ZAN)
            {
                DATZAngle *datZangle = static_cast<DATZAngle *>(GD.Records[i]);
                from = datZangle->From;
                to = datZangle->To;
                break;
            }
        }//end if on tag match
    }//end loop over dat records
}

void derivePoints()
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();
    bool valid = false;

    // Create a set of all the labels of used and unused points in the project
    // existingPointLabels is extended with the derived point label each time a unique derived
    // point is created, and is used to ensure only unique derived points are generated
    // NOTE: existingPointLabels will not appear correct in Qt debug mode, but values are still
    // correct
    std::set<std::string> existingPointLabels;
    for(map<string,posLLH_result>::iterator iter=GD.LSABin.posLLHResults.begin(); iter!=GD.LSABin.posLLHResults.end(); iter++)
    {
        std::string label = iter->first;
        existingPointLabels.insert(label);
    }

    //Fix to Bug #1395
    //find an ordered list (later points may depend on earlier points) of derived points to compute
    std::vector<std::string> ValidDerivedPointLabels = findValidDerivedDependencies();
    // Loop over derived points, in the order specified by findValidDerivedDependencies
    for(int i=0; i<ValidDerivedPointLabels.size(); i++)
    {
        // initialize line and fields objects - needed?
        std::string line("");
        std::vector<std::string> fields;

        std::string DerivedPointLabel;

        // loop over dat file lines associated with derived points
        for(int j=0; j<GD.DerivedPointDatStrings.size(); ++j)
        {
            // extact dat file line
            line = GD.DerivedPointDatStrings.at(j);
            fields = gnsstk::StringUtils::splitWithQuotes(line, ' ');
            // need to initialize label here?
            std::string label("");
            // if the derived point type extracted from the dat line is "MEAN":
            if(fields[0] == "MEAN")
            {
                // set label to derived point position label for this dat line
                label = fields[1];
            }
            // if the derived point type extracted from the dat line is "ENUO" (ENU offset):
            else if(fields[0] == "ENUO")
            {
                // set label to derived point position label for this dat line
                label = fields[2];
            }
            // if the extract label is equal to the current valid derived point label,
            // exit for loop
            if(label == ValidDerivedPointLabels.at(i)){
                DerivedPointLabel = label;
                break;
            }
        }

        // Check if derived point label already exists
        if (existingPointLabels.find(DerivedPointLabel) == existingPointLabels.end()){
            llhExternal adjustedLLH;
            xyzExternal adjustedXYZ;
            // If a mean derived point
            if (fields[0] == "MEAN"){
                valid = createDerivedPointFromMEAN(line, adjustedLLH, adjustedXYZ);
            }
            // If a ENU offset derived point
            else if (fields[0] == "ENUO") {
                valid = createDerivedPointFromENUO(line, adjustedLLH, adjustedXYZ);
            }

            // Now add this new derived point to the GD.DerivedPoints and GD.DerivedPointsXYZ objects
            if(valid){
                GD.DerivedPoints.insert(map<std::string,llhExternal>::value_type(adjustedLLH.label,adjustedLLH));
                GD.DerivedPointsXYZ.insert(map<std::string,xyzExternal>::value_type(adjustedXYZ.label,adjustedXYZ));
                existingPointLabels.insert(DerivedPointLabel); // don't allow duplicate derived points
            }
        }
        // otherwise the label already exists
        else{
            std::string errorMessage = "Warning - derived position " + DerivedPointLabel +
                    " uses a label that already exists.  No output position will be created.\n";
            std::cout << errorMessage;
        }
    }
}

//return an ordered list (later points may depend on earlier points) of derived points to compute
std::vector<std::string> findValidDerivedDependencies()
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();
    //create a set of derived point labels
    std::set<std::string> derivedPointLabels;
    std::vector<std::string> derivedPointLabelsVector;
    for(int i=0; i<GD.DerivedPointDatStrings.size(); i++)
    {
        std::string line = GD.DerivedPointDatStrings.at(i);
        std::vector<std::string> fields = gnsstk::StringUtils::splitWithQuotes(line, ' ');
        std::string label("");
        if(fields[0] == "MEAN")
        {
            label = fields[1];
        }
        else if(fields[0] == "ENUO")
        {
            label = fields[2];
        }
        derivedPointLabels.insert(label);
        derivedPointLabelsVector.push_back(label);
    }
    //check for duplicate derived point labels
    if(derivedPointLabels.size() < derivedPointLabelsVector.size())
    {
        std::sort(derivedPointLabelsVector.begin(), derivedPointLabelsVector.end());
        for(int i = 0; i < derivedPointLabelsVector.size() - 1; i++)
        {
            if(derivedPointLabelsVector[i] == derivedPointLabelsVector[i + 1])
            {
                std::string errorMessage = "Warning - derived position " + derivedPointLabelsVector[i + 1] +
                        " uses a label that already exists.  No output position will be created.\n";
                std::cout << errorMessage;
            }
        }
    }

    //map all derived point dependencies on other derived points
    std::map<std::string,std::set<std::string> > depMap;
    for(int i=0; i<GD.DerivedPointDatStrings.size(); i++)
    {
        std::string label("");
        std::set<std::string> deps;
        deps.clear();
        std::string line = GD.DerivedPointDatStrings.at(i);
        std::vector<std::string> fields = gnsstk::StringUtils::splitWithQuotes(line, ' ');
        if(fields[0] == "MEAN")
        {
            label = fields[1];
            for (int j = 4; j < fields.size(); ++j)
            {
                //only worry about derived point dependencies.  Normal points are not a concern.
                if(derivedPointLabels.find(fields[j]) != derivedPointLabels.end())
                    deps.insert(fields[j]);
            }
        }
        else if(fields[0] == "ENUO")
        {
            label = fields[2];
            //only worry about derived point dependencies.  Normal points are not a concern.
            if(derivedPointLabels.find(fields[1]) != derivedPointLabels.end())
                deps.insert(fields[1]);
        }

        depMap.insert(std::pair<std::string,std::set<std::string> >(label,deps));
    }

    //sort dependencies list independents first
    std::vector<std::string> returnList;
    std::map<std::string,std::set<std::string> >::iterator iter;
    for(iter=depMap.begin(); iter!=depMap.end(); iter++)
    {
        if(iter->second.size() == 0)
            returnList.push_back(iter->first);
    }
    for(int i=0;i<returnList.size();i++)
        depMap.erase(returnList.at(i));

    //iterate until size of returnList is unchanged (done or circular dependency)
    int lastReturnListSize = returnList.size();
    while(true)
    {
        //add dependent derived points
        for(iter=depMap.begin(); iter!=depMap.end(); iter++)
        {
            std::set<std::string> depSet = iter->second;
            std::set<std::string>::iterator it2;
            bool dependent = false;
            for(it2=depSet.begin(); it2!=depSet.end(); it2++)
            {
                if(depMap.find(*it2) != depMap.end())
                {
                    dependent = true;
                    break;
                }
            }
            if(!dependent)
            {
                returnList.push_back(iter->first);
            }
        }
        for(int i=0;i<returnList.size();i++)
            depMap.erase(returnList.at(i));
        if(returnList.size() == lastReturnListSize)
            break;
        else
            lastReturnListSize = returnList.size();
    }

    //warn of circular dependencies
    if(returnList.size() < derivedPointLabels.size())
    {
        for(iter=depMap.begin(); iter!=depMap.end(); iter++)
        {
            std::set<std::string> deps = iter->second;
            std::set<std::string>::iterator it2;
            std::string depList("");
            for(it2=deps.begin();it2!=deps.end();it2++)
                depList += (" " + *it2 + ",");
            depList.erase(depList.size()-1,1);
            std::string errorMessage = "Warning - derived position circular dependency. " + iter->first +
                    " depends on " + depList + ".  No output position will be created.\n";
            std::cout << errorMessage;
        }
    }

    return returnList;
}

void getConfidenceEllipseFromXYZCovariance(string confidence, double X, double Y, double Z, int ndof,
                                           double Cxx, double Cxy, double Cxz,double Cyy, double Cyz,
                                           double Czz, double &maj3D, double &maj2D, double &min2D,double &azim, double &vert)
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    gnsstk::Position pos(X, Y, Z, gnsstk::Position::Cartesian);
    gnsstk::Matrix<double> rot = northEastUpGeodetic(pos);

    // covariance
    Matrix<double> covXYZ(3,3);
    covXYZ(0,0) = Cxx;
    covXYZ(1,1) = Cyy;
    covXYZ(2,2) = Czz;
    covXYZ(0,1) = covXYZ(1,0) = Cxy;
    covXYZ(0,2) = covXYZ(2,0) = Cxz;
    covXYZ(1,2) = covXYZ(2,1) = Cyz;

    Matrix<double> covNEU = rot * covXYZ * transpose(rot);
    double Cnn = covNEU(0,0);
    double Cee = covNEU(1,1);
    double Cuu = covNEU(2,2);
    double Cne = covNEU(0,1);
    double Cnu = covNEU(0,2);
    double Ceu = covNEU(1,2);

    getScaledConfidenceEllipse(confidence, ndof, Cnn, Cne, Cnu, Cee, Ceu, Cuu, maj3D, maj2D, min2D, azim, vert);
}

enum_binary_file_status validateBinFile()
{
    GlobalDataLsapost& GD=GlobalDataLsapost::Instance();

    std::string binFileNameString = GD.binfile;
    QFile check;
    check.setFileName(QString::fromStdString(binFileNameString));
    if(!check.exists())
        return BIN_FILE_NOT_FOUND;

    //if the file exists, read it and check the hash code
    int stat;
    LSABinaryFile binCheck;
    try
    {
        stat = binCheck.ReadBinaryFile(binFileNameString);
    }
    catch(...)//handle case where .bin file format has changed, but developer forgot to update the Version
    {
        return BIN_FILE_NOT_PARSED;
    }

    if(stat != 0)
    {
        if(stat == 92)
        {
            return BIN_FILE_UNABLE_TO_OPEN;
        }
        else if(stat == 93)
        {
            return BIN_FILE_FORMAT_OBSOLETE;
        }
    }

    if(binCheck.status.size()==0)
        return BIN_FILE_NO_SOLUTION;

    return BIN_FILE_VALID;
}
